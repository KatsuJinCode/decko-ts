// The MARKED create route, measured against the PINNED DECK's own route
// table, verb matcher and fetch branch.
//
// The completeness register's A14 row grades the port on
// `match ":mark(.:format)" => "card#create", via: :post`
// (engine_routes.rb:36). This file pins both sides:
//
//   fixtures/captured/marked-create-route-ruby-oracle.json is what
//   oracle-capture-marked-create-route-ruby.rb (tests/server/) recorded by
//   EXECUTING the pinned deck's own route table against a recording Draw,
//   the pinned controller's before_action table, the pinned card gem's own
//   uri_fetch with the Card.new ask recorded, and the pinned actionpack's
//   own via -> request_method -> match_verb chain:
//
//     the route  engine_routes.rb:36, order 16 of 29, AFTER the typed
//                create (line 33, order 15) and BEFORE the (card)/create
//                arm (line 46, order 24). One segment: a two-segment path
//                is NOT this route.
//     the verb   via: :post - the PINNED actionpack turns that into
//                @via.map { Journey::Route.verb_matcher(v) }
//                (routing/mapper.rb:207-209) and the route matches only when
//                @request_method_match.any? { |m| m.call request }
//                (journey/route.rb:183-185), where VerbMatchers::POST is
//                `req.post?` (journey/route.rb:19-21). So this arm is a
//                POST-only route.
//     the table  create runs setup, authenticate, load_card, refresh_card -
//                NO load_mark. The mark rides the URL, never the implicit
//                ladder (rest.rb:10-12 is read-only; card_controller.rb:22
//                `before_action :load_mark, only: [:read]`).
//     the name   uri_fetch_opts' ||= : the URL mark names the new card,
//                underscores fold to spaces, and the body's card[name]
//                WINS over the URL mark.
//
//   The port's route table (src/server/write-routes.ts matchRoute) answers
//   the same shape: POST is the only verb that classifies as a marked
//   create, the arm's single-segment constraint is enforced, and the
//   precedence against the typed create and the (card)/create arm holds.
//   The .json suffix rides the mark until markToName (the port's
//   name-resolution layer) - the oracle's rows show the router's own
//   (.:format) capture splitting it before the fetch reads params[:mark],
//   so both sides resolve the same NAME. The live-HTTP create behavior
//   stays the write-routes suites' own pin.

import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { matchRoute } from "../../src/server/write-routes.js";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

const ORACLE = JSON.parse(
  readFileSync(path.join(REPO, "fixtures/captured/marked-create-route-ruby-oracle.json"), "utf8"),
) as {
  markedCreateRoute: { verb: string; patterns: string[]; requirements: Record<string, string>; action: string; order: number };
  markedCreateVia: string[];
  precedence: {
    typedCreateBefore: { order: number; action: string; patterns: string[] };
    explicitCreateAfter: { order: number; action: string; patterns: string[]; requirements: Record<string, string | string[]> };
  };
  beforeActionsForCreate: string[];
  uriFetch: Array<{ label: string; params: Record<string, unknown>; newAsks: Array<Record<string, unknown>>; error: string | null }>;
  createAction: Array<{ label: string; cardCalls: string[]; redirected: { url: string; status: number } | null; error: string | null }>;
  sources: Record<string, Array<{ line: number; text: string }>>;
};

describe("the marked create route, against the pinned deck gem", () => {
  it("the pinned deck registers match :mark(.:format) => card#create at order 16", () => {
    expect(ORACLE.markedCreateRoute.verb).toBe("match");
    expect(ORACLE.markedCreateRoute.patterns).toEqual([":mark(.:format)"]);
    expect(ORACLE.markedCreateRoute.action).toBe("card#create");
    expect(ORACLE.markedCreateRoute.order).toBe(16);
  });

  it("the arm is POST-only: via :post, and the pinned actionpack's own matcher is req.post?", () => {
    expect(ORACLE.markedCreateRoute.requirements).toEqual({ via: "post" });
    expect(ORACLE.markedCreateVia).toEqual(["post"]);
    // The source that enforces it: via -> request_method_match -> match_verb.
    // The matcher classes are generated by a class_eval template over VERBS,
    // so the verb predicate is the interpolated `req.<verb>?` and POST is one
    // of the eleven verbs that template builds (journey/route.rb:14-24).
    const verb = ORACLE.sources["pinnedVerbMatcher"]!;
    const verbSource = verb.map((row) => row.text).join("\n");
    expect(verbSource).toContain("VERBS = %w{ DELETE GET HEAD OPTIONS LINK PATCH POST PUT TRACE UNLINK }");
    expect(verbSource).toContain("def self.call(req); req.#{v.downcase}?; end");
    expect(verbSource).toContain("@request_method_match.any? { |m| m.call request }");
    const via = ORACLE.sources["pinnedViaToRequestMethod"]!;
    expect(via.map((row) => row.text).join("\n")).toContain("Journey::Route.verb_matcher");
  });

  it("precedence: the typed create (15) is before it, the (card)/create (24) is after it", () => {
    expect(ORACLE.precedence.typedCreateBefore.order).toBe(15);
    expect(ORACLE.markedCreateRoute.order).toBe(16);
    expect(ORACLE.precedence.explicitCreateAfter.order).toBe(24);
    expect(ORACLE.precedence.explicitCreateAfter.requirements["via"]).toEqual(["post", "patch"]);
  });

  it("create rides NO load_mark: setup, authenticate, load_card, refresh_card", () => {
    expect(ORACLE.beforeActionsForCreate).toEqual([
      "setup",
      "authenticate",
      "load_card",
      "refresh_card",
    ]);
    expect(ORACLE.beforeActionsForCreate).not.toContain("load_mark");
  });

  it("the URL mark names the new card; underscores fold; the body's card[name] wins", () => {
    const fromUrl = ORACLE.uriFetch[0]!;
    expect(fromUrl.error).toBeNull();
    expect(fromUrl.newAsks).toEqual([{ name: "Target" }]);
    const folded = ORACLE.uriFetch[1]!;
    expect(folded.newAsks).toEqual([{ name: "My Card" }]);
    const bodyWins = ORACLE.uriFetch[2]!;
    expect(bodyWins.newAsks).toEqual([{ name: "Other" }]);
  });

  it("the (.:format) capture separates the suffix BEFORE the fetch reads params[:mark]", () => {
    const suffixed = ORACLE.uriFetch[3]!;
    expect(suffixed.params["format"]).toBe("json");
    expect(suffixed.params["mark"]).toBe("Target");
    expect(suffixed.newAsks).toEqual([{ name: "Target" }]);
  });

  it("the create action asks card.save! and the success envelope redirects 303", () => {
    const create = ORACLE.createAction[0]!;
    expect(create.error).toBeNull();
    expect(create.cardCalls).toContain("save!");
    expect(create.redirected).toEqual({ url: "/", status: 303 });
  });
});

describe("the port's route table, against the pinned marked create", () => {
  it("POST /<mark> classifies as the marked create", () => {
    expect(matchRoute("POST", "/Target")).toEqual({ verb: "create", mark: "Target", json: false });
  });

  it("the arm is POST-only in the port too: PUT and PATCH classify as the marked update", () => {
    // The pinned matcher is req.post? (journey/route.rb:19-21); a PUT or
    // PATCH to the same one-segment path is the L37 update arm, not a create.
    expect(matchRoute("PUT", "/Target")).toEqual({ verb: "update", mark: "Target", json: false });
    expect(matchRoute("PATCH", "/Target")).toEqual({ verb: "update", mark: "Target", json: false });
    expect(matchRoute("DELETE", "/Target")).toEqual({ verb: "delete", mark: "Target", json: false });
  });

  it("the arm is ONE segment: a two-segment path is not the marked create", () => {
    expect(matchRoute("POST", "/a/b")).toBeNull();
  });

  it("precedence: /type/<x> is the typed create (15) and /card/create is the explicit arm (24)", () => {
    expect(matchRoute("POST", "/type/Foo")).toEqual({
      verb: "create",
      typeShortcut: "Foo",
      json: false,
    });
    expect(matchRoute("POST", "/card/create")).toEqual({ verb: "create", mark: undefined, json: false });
    // The BARE /type is the marked create of the card literally named
    // "type" (L36 needs one segment), never a typed create.
    expect(matchRoute("POST", "/type")).toEqual({ verb: "create", mark: "type", json: false });
  });

  it("the .json suffix rides the mark until markToName, the same name the oracle's split resolves", () => {
    // The route DOES declare (.:format), so Rails splits the suffix before
    // params[:mark] is read (the oracle's fourth row). The port keeps the
    // suffix on the mark and strips it in markToName - the port's
    // name-resolution layer, which also does the underscore fold the
    // oracle's second row measures. Both sides resolve the name "Target".
    expect(matchRoute("POST", "/Target.json")).toEqual({
      verb: "create",
      mark: "Target.json",
      json: false,
    });
    expect(matchRoute("POST", "/My_Card")).toEqual({ verb: "create", mark: "My_Card", json: false });
  });
});