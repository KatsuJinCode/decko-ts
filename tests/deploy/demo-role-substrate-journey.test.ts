import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { LocalSqliteDriver } from "../../src/server/drivers/local-sqlite.js";
import { FetchEngine } from "../../src/card/fetch.js";
import { createOwnerAccount, runAuthMigrations } from "../../src/card/auth/index.js";
import { CardActionEngine } from "../../src/card/actions/card-action-engine.js";
import {
  type ReadPermissionState,
  readPermissionStateFromViewerResults,
  readPermissionStatements,
} from "../../src/card/permissions/read-rules.js";
import { splitSqlStatements } from "../card/render/render-test-storage.js";
import { scratchDir } from "../support/scratch-dir.mjs";

const REPO_ROOT = fileURLToPath(new URL("../..", import.meta.url));

/** The chain a fresh deploy applies, in the order wrangler's migrations_dir
 *  walks it (wrangler.toml:56-63). */
const CHAIN = [
  "deploy/migrations/0001-schema.sql",
  "deploy/migrations/0002-card-text-binary-lookup-indexes.sql",
  "deploy/migrations/0003-demo-seed.sql",
  "deploy/migrations/0004-demo-account-substrate.sql",
] as const;
/** 0005 is applied separately so the CONTROL can stop at 0004. */
const ROLES_SUBSTRATE = "deploy/migrations/0006-demo-role-substrate.sql";

/** The eight codenames 0006 ships, with the real.yml line each is transcribed
 *  from (card-mod-account-0.20.0/data/real.yml). */
const ROLE_CODENAMES = {
  role: "real.yml:4-10", // the Role cardtype
  members: "real.yml:12-13", // the *members roles list card
  anyone: "real.yml:18-23",
  anyone_signed_in: "real.yml:24-29",
  administrator: "real.yml:30-41",
  eagle: "real.yml:42-46",
  shark: "real.yml:47-57",
  help_desk: "real.yml:58-68",
} as const;

interface Deck {
  readonly path: string;
  readonly driver: LocalSqliteDriver;
  readonly fetcher: FetchEngine;
  /** The Decko Bot actor card 0004 created (id 1130) — every seeded row's
   *  creator, and the engine actor the journey writes under
   *  (first-run-setup.ts:675, :710). */
  bot(): Promise<{ id: number; name: string }>;
  cardCount(): Promise<number>;
  idForCodename(codename: string): Promise<number>;
  /** The permission state a signed-in viewer resolves to — the port of
   *  account_holder.rb's read_rules_hash construction
   *  (read-rules.ts:284-346). */
  readState(viewer: { signedIn: boolean; actorId?: number }): Promise<ReadPermissionState>;
  close(): void;
}

const openDecks: string[] = [];

afterEach(() => {
  for (const path of openDecks.splice(0)) {
    try {
      rmSync(path, { force: true });
    } catch {
      // A Windows file lock on a driver this test already closed is not worth
      // failing a green journey over; the temp dir is under os.tmpdir().
    }
  }
  for (const key of ["DECKO_FIRST_RUN", "DECKO_WRITE_PATH"]) delete process.env[key];
});

/** The deploy demo profile (first-run-setup.ts:183-197): both gates on. */
function armDemoProfile(): void {
  process.env.DECKO_FIRST_RUN = "1";
  process.env.DECKO_WRITE_PATH = "1";
}

/**
 * Build a temp database with the migration chain applied, using node:sqlite.
 *
 * `withRoles: false` stops at 0004 — the control the journey proof needs: the
 * 0001..0004 chain exactly as it shipped before this port.
 */
async function deck(opts: { withRoles?: boolean; applyRolesTwice?: boolean } = {}): Promise<Deck> {
  const dir = scratchDir("decko-demo-roles-");
  const path = join(dir, "demo.sqlite");
  openDecks.push(path);

  const db = new DatabaseSync(path);
  try {
    for (const file of CHAIN) {
      for (const statement of splitSqlStatements(readFileSync(join(REPO_ROOT, file), "utf8"))) {
        db.exec(statement);
      }
    }
    if (opts.withRoles !== false) {
      const substrate = readFileSync(join(REPO_ROOT, ROLES_SUBSTRATE), "utf8");
      for (const statement of splitSqlStatements(substrate)) db.exec(statement);
      if (opts.applyRolesTwice === true) {
        // The idempotence gate: the SAME bytes, applied a second time.
        for (const statement of splitSqlStatements(substrate)) db.exec(statement);
      }
    }
  } finally {
    db.close();
  }

  const driver = new LocalSqliteDriver({ path });
  await runAuthMigrations(driver);
  return {
    path,
    driver,
    fetcher: new FetchEngine(driver),
    async bot() {
      const row = await driver.query<{ id: number; name: string }>(
        "SELECT id, name FROM cards WHERE codename = 'decko_bot'",
        [],
      );
      const found = row.rows[0];
      if (found === undefined) throw new Error("0004 did not ship the Decko Bot actor card");
      return found;
    },
    async cardCount() {
      const result = await driver.query<{ n: number }>("SELECT COUNT(*) AS n FROM cards", []);
      return Number(result.rows[0]?.n ?? 0);
    },
    async idForCodename(codename) {
      const row = await driver.query<{ id: number }>(
        "SELECT id FROM cards WHERE codename = ? AND trash = 0",
        [codename],
      );
      const found = row.rows[0];
      if (found === undefined) throw new Error(`codename ${codename} does not resolve`);
      return found.id;
    },
    async readState(viewer) {
      return readPermissionStateFromViewerResults(
        await driver.batch(readPermissionStatements(viewer)),
        viewer,
      );
    },
    close() {
      driver.close();
    },
  };
}

/** The setup-created owner, through the real engine (first-run-setup.ts:668-760). */
async function createOwner(d: Deck): Promise<{ id: number; name: string }> {
  const created = await createOwnerAccount(
    { driver: d.driver, fetcher: d.fetcher },
    { email: OWNER_EMAIL, password: OWNER_PASSWORD },
  );
  if (!created.ok) throw new Error(`create failed: ${created.reason} ${created.message}`);
  return { id: created.owner.id, name: created.owner.name };
}

// A password that clears Ruby's two create-time ladders
// (right/password.rb:28-34 length >= 8, :36-49 the four character classes).
const OWNER_EMAIL = "owner@demo.invalid";
const OWNER_PASSWORD = "Demo-Setup-1";

/**
 * THE GRANT — the port's own role-setting path, exercised through the real
 * CardActionEngine. See the DIVERGENCE block in the file header: this is the
 * `[[Link]]` content form the port's reference path understands, standing in
 * for Ruby's IdList `~<id>` pointer form, whose write path is not ported
 * (card-mod-list.ts:1024-1031).
 */
async function grantRole(d: Deck, roleName: string, memberName: string): Promise<number> {
  const bot = await d.bot();
  const engine = new CardActionEngine(d.fetcher, { actor: bot });
  const card = await engine.createCard({
    name: `${roleName}+*members`,
    content: `[[${memberName}]]`,
  });
  return card.cardId;
}

describe("the deploy demo deck's role surface (0001 -> 0004 + 0006)", () => {
  it("CONTROL: 0001..0004 alone resolve NO roles and NO role parties for a signed-in viewer", async () => {
    armDemoProfile();
    const d = await deck({ withRoles: false });
    const owner = await createOwner(d);

    // The two codename lookups rolePartyStatement issues
    // (read-rules.ts:244-248) both select NULL, so its own WHERE matches
    // nothing. Reproduced through the public state, not asserted from a string.
    for (const codename of ["role", "members", "anyone", "anyone_signed_in", "administrator"]) {
      const row = await d.driver.query<{ n: number }>(
        "SELECT COUNT(*) AS n FROM cards WHERE codename = ? AND trash = 0",
        [codename],
      );
      expect(Number(row.rows[0]?.n ?? 0), `codename ${codename} unexpectedly present`).toBe(0);
    }

    const state = await d.readState({ signedIn: true, actorId: owner.id });
    // account_holder.rb:111-113 `fetch_roles` returns [AnyoneSignedInID] plus
    // the member lists of the actor's roles. On this deck EVERY ONE of those is
    // absent, so the only party left is the actor itself
    // (read-rules.ts:322-323 `parties.push(...actorId)`).
    expect(state.parties).toEqual([owner.id]);
    // And the Administrator arm of always_ok? is unreachable
    // (read-rules.ts:305, :314-318 — `administratorId` is undefined).
    expect(state.alwaysOk).toBe(false);
    d.close();
  });

  it("0006 carries the Role cardtype, the roles list card and all six real.yml roles", async () => {
    const d = await deck();
    const ids: Record<string, number> = {};
    for (const [codename, citation] of Object.entries(ROLE_CODENAMES)) {
      const row = await d.driver.query<{ id: number; name: string; type_id: number | null }>(
        "SELECT id, name, type_id FROM cards WHERE codename = ? AND trash = 0",
        [codename],
      );
      const found = row.rows[0];
      expect(found, `codename ${codename} (${citation}) missing from 0006`).toBeDefined();
      ids[codename] = found!.id;
    }
    // The names are the gem's, not this suite's invention.
    const names = await d.driver.query<{ name: string }>(
      `SELECT name FROM cards WHERE codename IN
         ('role','members','anyone','anyone_signed_in','administrator','eagle','shark','help_desk')
       ORDER BY name`,
      [],
    );
    expect(names.rows.map((r) => r.name)).toEqual([
      // SQLite's BINARY collation puts '*' (0x2A) before 'A' (0x41).
      "*members",
      "Administrator",
      "Anyone",
      "Anyone Signed In",
      "Eagle",
      "Help Desk",
      "Role",
      "Shark",
    ]);

    // The relation that carries the whole surface: every role's type_id is the
    // Role CARDTYPE's id. That is the type filter
    // `roles.type_id = (SELECT id FROM cards WHERE codename = 'role')`
    // (read-rules.ts:247-248) — without it the rolehash search matches no row.
    for (const role of [
      "anyone",
      "anyone_signed_in",
      "administrator",
      "eagle",
      "shark",
      "help_desk",
    ]) {
      const row = await d.driver.query<{ type_id: number | null }>(
        "SELECT type_id FROM cards WHERE codename = ?",
        [role],
      );
      expect(row.rows[0]?.type_id, `${role} is not typed by the Role cardtype`).toBe(ids.role);
    }
    // And the cardtype is self-typed, as cards_003 / cards_006 are in the core
    // fixture (real.yml:5 declares `:type: :cardtype`).
    const cardtype = await d.driver.query<{ type_id: number | null }>(
      "SELECT type_id FROM cards WHERE codename = 'role'",
      [],
    );
    expect(cardtype.rows[0]?.type_id).toBe(ids.role);

    // `*members` is declared with no `:type:` (real.yml:12-13), so it takes the
    // deck DEFAULT type — the same rule 0004 applied to Anonymous.
    const members = await d.driver.query<{ type_id: number | null }>(
      "SELECT type_id FROM cards WHERE codename = 'members'",
      [],
    );
    expect(members.rows[0]?.type_id).toBe(await d.idForCodename("basic"));
    d.close();
  });

  it("a signed-in viewer's parties now carry Anyone and Anyone Signed In before any membership", async () => {
    armDemoProfile();
    const d = await deck();
    const owner = await createOwner(d);
    const state = await d.readState({ signedIn: true, actorId: owner.id });
    // account_holder.rb:111-113 `fetch_roles` opens with AnyoneSignedInID;
    // read-rules.ts:320-322 puts Anyone first and Anyone Signed In second.
    // The CONTROL above is the point of this test: on 0004 that list was
    // [ownerId] alone.
    expect(state.parties).toEqual([
      await d.idForCodename("anyone"),
      await d.idForCodename("anyone_signed_in"),
      owner.id,
    ]);
    // No membership yet, so the Administrator arm is still false.
    expect(state.alwaysOk).toBe(false);
    d.close();
  });

  it("THE GRANT: adding the owner to Administrator+*members flips alwaysOk through the real engine", async () => {
    armDemoProfile();
    const d = await deck();
    const owner = await createOwner(d);
    expect((await d.readState({ signedIn: true, actorId: owner.id })).alwaysOk).toBe(false);

    const memberCardId = await grantRole(d, "Administrator", owner.name);

    // The engine wrote BOTH halves of the row the rolehash reads:
    //   * the `<Role>+*members` junction — left = the role card, right = the
    //     `*members` codename card (read-rules.ts:239-246);
    //   * the card_references row naming the member (read-rules.ts:239-243),
    //     which the port's reference path builds from the `[[link]]` content
    //     chunk (refresh-references-out.ts:121-139, :251-293).
    const junction = await d.driver.query<{ left_id: number; right_id: number }>(
      `SELECT left_id, right_id FROM cards
       WHERE left_id = (SELECT id FROM cards WHERE codename = 'administrator')
         AND right_id = (SELECT id FROM cards WHERE codename = 'members')
         AND trash = 0`,
      [],
    );
    expect(junction.rows.length).toBe(1);
    const reference = await d.driver.query<{ referer_id: number; ref_type: string }>(
      "SELECT referer_id, ref_type FROM card_references WHERE referer_id = ?",
      [memberCardId],
    );
    expect(reference.rows).toEqual([{ referer_id: memberCardId, ref_type: "L" }]);

    // And the permission state now says what Ruby's always_ok? says
    // (auth/permissions.rb:8-13 -> account_holder.rb:63-65
    // `all_enabled_roles.include? AdministratorID`).
    const after = await d.readState({ signedIn: true, actorId: owner.id });
    expect(after.alwaysOk).toBe(true);
    expect(after.parties).toContain(await d.idForCodename("administrator"));
    d.close();
  });

  it("THE GRANT IS SCOPED: an actor outside the member list gets nothing, and Anonymous is unaffected", async () => {
    armDemoProfile();
    const d = await deck();
    const owner = await createOwner(d);
    await grantRole(d, "Administrator", owner.name);

    // A second signed-in actor that is NOT in the member list.
    const bot = await d.bot();
    const stranger = await d.driver.query<{ id: number }>(
      "SELECT id FROM cards WHERE name = 'About'",
      [],
    );
    expect(stranger.rows[0], "0003's About card is the non-member actor").toBeDefined();

    const strangerState = await d.readState({ signedIn: true, actorId: stranger.rows[0].id });
    expect(strangerState.alwaysOk).toBe(false);
    expect(strangerState.parties).not.toContain(await d.idForCodename("administrator"));

    // Anonymous is signed OUT (account_holder.rb:39-41 — all_enabled_roles is
    // [] when id == AnonymousID), so it joins no roles whatever the member list
    // says; the Decko Bot is a different arm entirely (actor === deckoBot,
    // read-rules.ts:317).
    const anonymous = await d.readState({
      signedIn: false,
      actorId: await d.idForCodename("anonymous"),
    });
    expect(anonymous.alwaysOk).toBe(false);
    expect(anonymous.parties).not.toContain(await d.idForCodename("administrator"));

    // And the bot's own always_ok? short-circuit ("cannot disable",
    // auth/permissions.rb:9) still fires, so the grant did not disturb it.
    const botState = await d.readState({ signedIn: true, actorId: bot.id });
    expect(botState.alwaysOk).toBe(true);
    d.close();
  });

  it("a non-administrator role grants the ROLE but not alwaysOk", async () => {
    // Eagle is a real.yml role with no always_ok? consequence
    // (real.yml:42-46 — the always_ok? arms are the DeckoBot actor and the
    // Administrator role only, read-rules.ts:317-318). This pins that the port
    // does not treat every role as administrator.
    armDemoProfile();
    const d = await deck();
    const owner = await createOwner(d);
    await grantRole(d, "Eagle", owner.name);
    const state = await d.readState({ signedIn: true, actorId: owner.id });
    expect(state.parties).toContain(await d.idForCodename("eagle"));
    expect(state.alwaysOk).toBe(false);
    d.close();
  });

  it("IDEMPOTENCE: applying 0006 twice inserts nothing the second time, and the journey still runs", async () => {
    armDemoProfile();
    const once = await deck();
    const onceCount = await once.cardCount();
    once.close();

    const twice = await deck({ applyRolesTwice: true });
    const twiceCount = await twice.cardCount();
    expect(twiceCount).toBe(onceCount);
    // 0003's four cards + 0004's nineteen rows + 0005's eight.
    expect(twiceCount).toBe(31);

    // And the deck is still fully functional after the second application: the
    // owner creates, the role grants, and the permission state agrees.
    const owner = await createOwner(twice);
    expect((await twice.readState({ signedIn: true, actorId: owner.id })).alwaysOk).toBe(false);
    await grantRole(twice, "Administrator", owner.name);
    expect((await twice.readState({ signedIn: true, actorId: owner.id })).alwaysOk).toBe(true);
    twice.close();
  });
});
