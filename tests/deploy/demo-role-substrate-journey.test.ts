// The deploy demo deck's ROLE surface, end to end, over the real migration
// chain: 0001 schema -> 0002 indexes -> 0003 demo seed -> 0004 account
// substrate -> 0006 role substrate, then create-owner -> grant-the-owner-a-role
// -> read the permission state back.
//
// WHY THIS FILE EXISTS. The demo-account-seeding port (972b727) shipped the
// account system and deliberately shipped NO roles, recording the omission in
// its own migration header (deploy/migrations/0004-demo-account-substrate.sql
// "NOT INCLUDED ... roles ... None is read by the census, the create, or
// signinAccount"). That is true and it is the wrong reason: the deck then has
// no role set at all, so the account permission surface has nothing to grant.
// Concretely, src/card/permissions/read-rules.ts:236-252 (rolePartyStatement,
// the port of Self::Role.generate_rolehash — card-mod-account-0.20.0
// set/self/role.rb:33-40) resolves NO roles for ANY actor, because
// `lists.right_id = (SELECT id FROM cards WHERE codename = 'members')`
// (:244-245) and `roles.type_id = (SELECT id FROM cards WHERE codename =
// 'role')` (:247-248) both select NULL on a 0001..0004 deck. `alwaysOk`
// (read-rules.ts:314-318) is then reachable only through the Decko Bot arm
// (:317), never through the Administrator arm (:318).
// deploy/migrations/0006-demo-role-substrate.sql (generated by
// deploy/seed-role-substrate.mjs) is the fix, and this file is the proof that
// it is a fix and not a plausible-looking file.
//
// WHAT IS PROVEN, and against which Ruby source:
//
//   1. CONTROL: on 0001..0004 alone a signed-in viewer's party list carries NO
//      role ids at all — the exact hole the suite was handed, reproduced rather
//      than asserted from a comment. The codename lookups read-rules.ts:244-248
//      issue both select NULL, so the `anyone` / `anyone_signed_in` parties
//      (read-rules.ts:303-304, :320-322, the port of account_holder.rb:111-113
//      `[AnyoneSignedInID] + ...`) are absent too.
//   2. 0006 makes the eight real.yml codenames resolve — the Role cardtype
//      (card-mod-account-0.20.0/data/real.yml:4-10), the `*members` roles list
//      card (:12-13) and all six roles (:18-23, :24-29, :30-41, :42-46,
//      :47-57, :58-68) — and every role's type_id is the Role cardtype's id,
//      which is the relation the rolehash search keys on.
//   3. A signed-in viewer's parties now carry Anyone and Anyone Signed In
//      before any membership exists: the role surface RESOLVES.
//   4. THE GRANT. The port DOES have a role-grant path and this file pins it:
//      creating the card `Administrator+*members` with a link to the owner
//      through the real CardActionEngine writes the `<Role>+*members` junction
//      AND the card_references row the rolehash reads
//      (src/card/actions/refresh-references-out.ts:75-101 / :121-139, the port
//      of lib/card/reference/all.rb:47-50 / :54-62), and the owner's
//      permission state flips `alwaysOk` false -> true — the port of
//      auth/permissions.rb:8-13 `always_ok?` -> account_holder.rb:63-65
//      `role? AdministratorID`.
//   5. THE GRANT IS SCOPED. An actor that is not in the member list does NOT
//      get alwaysOk, and the signed-out Anonymous viewer is unaffected — so the
//      substrate did not open a hole.
//   6. IDEMPOTENCE: applying 0006 twice inserts nothing the second time, and
//      the whole journey still runs against the twice-applied database.
//
// THE GRANT'S SHAPE. Ruby's grant is the IdList form:
// card-mod-list-0.20.0/set/abstract/id_list.rb:3-5 stores items as `~<id>`,
// and :33-47 overrides create_references_out to write one
// `{referer_id, referee_id, referee_key: nil, ref_type: "L"}` row per item.
// The engine does the same for Role+*members by its set, whatever the card's
// own type (list-content.ts standardizeIdListContent and isListCard): the
// `[[Link]]` content below is stored as `~<id>` and its reference row is the
// id-list row. The checkbox UI that would drive it (card-mod-account
// set/type/role.rb:26-32 `add_item`/`drop_item` against `+*disabled roles`)
// is not ported; the `add_item` / `drop_item` events are declarations only
// (src/card/mod-loader/mods/card-mod-list.ts).
//
// NOT IN tests/standing-net.json — recorded in the receipt, same as the
// 0004 journey.
//
// STORAGE. A real temp FILE built by node:sqlite (DatabaseSync): the SQL files
// are applied exactly as `wrangler d1 execute --file` would apply them, in
// migration order, and the engine then opens that same file through the real
// LocalSqliteDriver. Nothing about the data is hand-assembled in TS.

