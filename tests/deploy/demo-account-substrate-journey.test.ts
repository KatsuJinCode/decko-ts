// The DEPLOY demo deck's first-run journey, end to end, over the real
// migration chain: 0001 schema -> 0002 indexes -> 0003 demo seed -> 0004
// account substrate, then census -> /setup create-owner -> signinAccount.
//
// WHY THIS FILE EXISTS. The first-run port (35e7b93,
// docs/first-run-demo-profile.md) built /setup and named the blocker it could
// not code around: the shipped content chain carries no account system, so
// setupWindowState answers `account_system_absent`, /setup 404s with "This
// deck has no account system", and signin has no actor cards. The engine has
// no mod-seeding capability, so deploy/migrations/0004-demo-account-substrate.sql
// (generated by deploy/seed-account-system.mjs) is the fix, and this file is
// the proof that it is a fix and not a plausible-looking file.
//
// WHAT IS PROVEN, and against which Ruby source:
//
//   1. CONTROL: on 0001..0003 alone the window reports `account_system_absent`
//      — the exact blocker the suite was handed, reproduced rather than
//      asserted from the error string.
//   2. 0004 makes the account codenames resolve (card-mod-account-0.20.0
//      data/real.yml:80-151, the `*account` right card and its four field
//      cards) and the two system actors resolve by codename
//      (actor.ts:74-87 over card-1.110.0/lib/card/codename.rb:108).
//   3. The census reads ZERO, because the only seeded `+*account` row's HOLDER
//      is Decko Bot (auth/setup.rb:43-46; card-mod-account
//      set/self/anonymous.rb:3-6 is why Anonymous has no junction).
//   4. createOwnerAccount succeeds — a real CardActionEngine write over the
//      same driver, producing the six rows first-run-setup.ts:726-749 creates.
//   5. The window CLOSES: count goes 0 -> 1, reason `needs_setup` ->
//      `setup_complete`. This is the half that the port's documented deviation
//      (countUserAccounts counts by HOLDER, not creator_id) exists for.
//   6. signinAccount succeeds with the owner's own email and password, and
//      issues a real session row — the journey's last step.
//   7. A second application of 0004 changes nothing: the file is idempotent
//      by construction, and the journey still runs against the twice-applied
//      database.
//
// STORAGE. A real temp FILE built by node:sqlite (DatabaseSync), because the
// ask names node:sqlite and because a file is what a D1 database is: the SQL
// files are applied exactly as `wrangler d1 execute --file` would apply them,
// in migration order, and the engine then opens that same file through the
// real LocalSqliteDriver. Nothing about the data is hand-assembled in TS.
//
// NOT IN tests/standing-net.json — recorded in the receipt.

import { DatabaseSync } from "node:sqlite";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, describe, expect, it } from "vitest";
import { LocalSqliteDriver } from "../../src/server/drivers/local-sqlite.js";
import { FetchEngine } from "../../src/card/fetch.js";
import {
  createOwnerAccount,
  runAuthMigrations,
  SessionStore,
  setupWindowState,
  signinAccount,
} from "../../src/card/auth/index.js";
import { splitSqlStatements } from "../card/render/render-test-storage.js";
import { scratchDir } from "../support/scratch-dir.mjs";

const REPO_ROOT = fileURLToPath(new URL("../..", import.meta.url));

/** The chain a fresh deploy applies, in the order wrangler's
 *  migrations_dir walks it (wrangler.toml:56-63). */
const CHAIN = [
  "deploy/migrations/0001-schema.sql",
  "deploy/migrations/0002-card-text-binary-lookup-indexes.sql",
  "deploy/migrations/0003-demo-seed.sql",
] as const;
const SUBSTRATE = "deploy/migrations/0004-demo-account-substrate.sql";

interface Deck {
  readonly path: string;
  readonly driver: LocalSqliteDriver;
  readonly fetcher: FetchEngine;
  cardCount(): Promise<number>;
  close(): void;
}

const openDecks: string[] = [];

afterEach(() => {
  for (const path of openDecks.splice(0)) {
    try {
      rmSync(path, { force: true });
    } catch {
      // A Windows file lock on a driver this test already closed is not worth
      // failing a green journey over; the temp dir is under os.tmpdir().
    }
  }
  for (const key of ["DECKO_FIRST_RUN", "DECKO_WRITE_PATH"]) delete process.env[key];
});

/** The deploy demo profile (first-run-setup.ts:183-197): both gates on. */
function armDemoProfile(): void {
  process.env.DECKO_FIRST_RUN = "1";
  process.env.DECKO_WRITE_PATH = "1";
}

/**
 * Build a temp database with the migration chain applied, using node:sqlite.
 *
 * `withSubstrate: false` reproduces the blocker the suite was handed — the
 * 0001..0003 chain exactly as it shipped — which is the control the journey
 * proof needs.
 */
async function deck(opts: { withSubstrate?: boolean; applySubstrateTwice?: boolean } = {}): Promise<Deck> {
  const dir = scratchDir("decko-demo-account-");
  const path = join(dir, "demo.sqlite");
  openDecks.push(path);

  const db = new DatabaseSync(path);
  try {
    for (const file of CHAIN) {
      for (const statement of splitSqlStatements(readFileSync(join(REPO_ROOT, file), "utf8"))) {
        db.exec(statement);
      }
    }
    if (opts.withSubstrate !== false) {
      const substrate = readFileSync(join(REPO_ROOT, SUBSTRATE), "utf8");
      for (const statement of splitSqlStatements(substrate)) db.exec(statement);
      if (opts.applySubstrateTwice === true) {
        // The idempotence gate: the SAME bytes, applied a second time.
        for (const statement of splitSqlStatements(substrate)) db.exec(statement);
      }
    }
  } finally {
    db.close();
  }

  const driver = new LocalSqliteDriver({ path });
  await runAuthMigrations(driver);
  return {
    path,
    driver,
    fetcher: new FetchEngine(driver),
    async cardCount() {
      const result = await driver.query<{ n: number }>("SELECT COUNT(*) AS n FROM cards", []);
      return Number(result.rows[0]?.n ?? 0);
    },
    close() {
      driver.close();
    },
  };
}

// A password that clears Ruby's two create-time ladders
// (right/password.rb:28-34 length >= 8, :36-49 the four character classes).
const OWNER_EMAIL = "owner@demo.invalid";
const OWNER_PASSWORD = "Demo-Setup-1";

describe("the deploy demo deck's first-run journey (0001 -> 0004)", () => {
  it("CONTROL: 0001..0003 alone answer account_system_absent — the blocker the lane was handed", async () => {
    armDemoProfile();
    const d = await deck({ withSubstrate: false });
    const state = await setupWindowState({ driver: d.driver });
    // Reproduced, not asserted from a string: this is the honest state of a
    // demo database provisioned by the pre-existing chain, and it is what /setup
    // 404s on (first-run-routes.ts; SETUP_CLOSED_MESSAGE.account_system_absent).
    expect(state.reason).toBe("account_system_absent");
    expect(state.open).toBe(false);
    // And the substrate is what is missing, not the deck: 0003's four cards
    // are there and render.
    expect(await d.cardCount()).toBe(4);
    d.close();
  });

  it("0004 carries the account substrate: the five codenames and the two system actors resolve", async () => {
    const d = await deck();
    // The five field cards signin.ts:108 reads. Without all five,
    // resolveAccountCodenameIds returns null and every signin is
    // `account_system_absent` (signin.ts:256-257).
    for (const codename of ["account", "email", "password", "salt", "status"]) {
      const row = await d.driver.query<{ id: number }>(
        "SELECT id FROM cards WHERE codename = ? AND trash = 0",
        [codename],
      );
      expect(row.rows[0], `codename ${codename} missing from 0004`).toBeDefined();
    }
    // The two actors auth/setup.rb:44 names: "every deck starts with two
    // accounts: DeckoBot and Anonymous". Resolved by CODENAME, the mechanism
    // the gem itself uses (codename.rb:108), not by a hardcoded id.
    const actors = await d.driver.query<{ codename: string; name: string }>(
      "SELECT codename, name FROM cards WHERE codename IN ('decko_bot', 'anonymous') AND trash = 0 ORDER BY codename",
      [],
    );
    expect(actors.rows).toEqual([
      { codename: "anonymous", name: "Anonymous" },
      { codename: "decko_bot", name: "Decko Bot" },
    ]);
    d.close();
  });

  it("the census reads ZERO on the seeded deck — Decko Bot's account is the only one", async () => {
    armDemoProfile();
    const d = await deck();
    const junctions = await d.driver.query<{ left_id: number; n: number }>(
      "SELECT left_id, COUNT(*) AS n FROM cards WHERE right_id = (SELECT id FROM cards WHERE codename = 'account') GROUP BY left_id",
      [],
    );
    // ONE seeded junction, and its holder is the bot. Ruby seeds no Anonymous
    // account: set/self/anonymous.rb:3-6 overrides `account` to nil and
    // `account?` to false. (The port's own first-run FIXTURE seeds two —
    // tests/card/auth/first-run-setup.test.ts:159-160 — a fixture choice, not
    // oracle truth; the census excludes both holders either way.)
    expect(junctions.rows.length).toBe(1);
    const bot = await d.driver.query<{ id: number }>(
      "SELECT id FROM cards WHERE codename = 'decko_bot'",
      [],
    );
    expect(junctions.rows[0].left_id).toBe(bot.rows[0].id);

    const state = await setupWindowState({ driver: d.driver });
    expect(state.reason).toBe("needs_setup");
    expect(state.open).toBe(true);
    expect(state.accountCount).toBe(0);
    d.close();
  });

  it("THE JOURNEY: census -> create-owner -> window closed -> real signin succeeds", async () => {
    armDemoProfile();
    const d = await deck();

    // 1. the window is open
    expect((await setupWindowState({ driver: d.driver })).reason).toBe("needs_setup");

    // 2. the owner create, through the real CardActionEngine
    const created = await createOwnerAccount(
      { driver: d.driver, fetcher: d.fetcher },
      { email: OWNER_EMAIL, password: OWNER_PASSWORD },
    );
    expect(created.ok).toBe(true);
    if (!created.ok) throw new Error(`create failed: ${created.reason} ${created.message}`);

    // The email is stored downcased (right/email.rb:29-33 downcase_email).
    const storedEmail = await d.driver.query<{ db_content: string | null }>(
      "SELECT db_content FROM cards WHERE id = ?",
      [created.fieldCardIds.email],
    );
    expect(storedEmail.rows[0]?.db_content).toBe(OWNER_EMAIL);
    // The status child is the "active" the create-time event writes
    // (right/account/events.rb:7-9, abstract/account_holder.rb:24-26).
    const storedStatus = await d.driver.query<{ db_content: string | null }>(
      "SELECT db_content FROM cards WHERE id = ?",
      [created.fieldCardIds.status],
    );
    expect(storedStatus.rows[0]?.db_content).toBe("active");
    // The stored password is the SHA-1 digest, never the plaintext.
    const storedPassword = await d.driver.query<{ db_content: string | null }>(
      "SELECT db_content FROM cards WHERE id = ?",
      [created.fieldCardIds.password],
    );
    expect(storedPassword.rows[0]?.db_content).toMatch(/^[0-9a-f]{40}$/);
    expect(storedPassword.rows[0]?.db_content).not.toBe(OWNER_PASSWORD);

    // 3. the window CLOSES. This is the step the port's documented deviation
    //    exists for: Ruby's literal `creator_id: ["ne", DeckoBotID]`
    //    (setup.rb:43-46) cannot see this row, because the port's engine stamps
    //    a bot-authored create with the bot's id (one actor, where Ruby splits
    //    as_id from current_id — the full mechanism is on countUserAccounts).
    const after = await setupWindowState({ driver: d.driver });
    expect(after.reason).toBe("setup_complete");
    expect(after.open).toBe(false);
    expect(after.accountCount).toBe(1);

    // 4. the real signin: the owner's own email + password, through
    //    signinAccount, producing a real auth_sessions row.
    const sessions = new SessionStore({ driver: d.driver });
    const signin = await signinAccount(d.driver, sessions, OWNER_EMAIL, OWNER_PASSWORD);
    expect(signin.ok).toBe(true);
    if (!signin.ok) throw new Error(`signin failed: ${signin.reason} ${signin.message}`);
    // The session's actor is the HOLDER, not the +*account junction
    // (signin.rb:48 `Auth.signin account.left_id`).
    expect(signin.actor.id).toBe(created.owner.id);
    expect(signin.session.token).toBeTruthy();

    // The token resolves back to the owner, which is what "signed in" means.
    const resolved = await sessions.resolveActorFromToken(signin.session.token);
    expect(resolved?.id).toBe(created.owner.id);
    expect(resolved?.name).toBe(created.owner.name);

    d.close();
  });

  it("a wrong password is still wrong_password — the substrate did not open a hole", async () => {
    armDemoProfile();
    const d = await deck();
    const created = await createOwnerAccount(
      { driver: d.driver, fetcher: d.fetcher },
      { email: OWNER_EMAIL, password: OWNER_PASSWORD },
    );
    expect(created.ok).toBe(true);
    const sessions = new SessionStore({ driver: d.driver });
    const signin = await signinAccount(d.driver, sessions, OWNER_EMAIL, `${OWNER_PASSWORD}x`);
    expect(signin.ok).toBe(false);
    if (signin.ok) throw new Error("unreachable");
    // signin.rb:80 `:error_wrong_password` — the exact en.yml string.
    expect(signin.reason).toBe("wrong_password");
    expect(signin.message).toBe("Wrong password");
    d.close();
  });

  it("Decko Bot's own account cannot be signed in to (no +*password child, as Ruby ships it)", async () => {
    // card-mod-account real.yml gives the [:decko_bot, :account] entry an
    // :email and the create-time events give it +*salt and +*status — but
    // encrypt_password (right/password.rb:19-26) only fires on a +*password
    // save, and there is none. The stored digest is therefore absent and no
    // password can match it (signin.ts:276-280: Ruby nil == String is false).
    armDemoProfile();
    const d = await deck();
    const sessions = new SessionStore({ driver: d.driver });
    const signin = await signinAccount(d.driver, sessions, "no-reply@decko.org", "anything at all");
    expect(signin.ok).toBe(false);
    if (signin.ok) throw new Error("unreachable");
    expect(signin.reason).toBe("wrong_password");
    d.close();
  });

  it("IDEMPOTENCE: applying 0004 twice inserts nothing the second time, and the journey still runs", async () => {
    armDemoProfile();
    const once = await deck();
    const onceCount = await once.cardCount();
    once.close();

    const twice = await deck({ applySubstrateTwice: true });
    const twiceCount = await twice.cardCount();
    expect(twiceCount).toBe(onceCount);
    // 0003's four cards plus 0004's nineteen rows.
    expect(twiceCount).toBe(23);

    // And the deck is still fully functional after the second application.
    const state = await setupWindowState({ driver: twice.driver });
    expect(state.reason).toBe("needs_setup");
    const created = await createOwnerAccount(
      { driver: twice.driver, fetcher: twice.fetcher },
      { email: OWNER_EMAIL, password: OWNER_PASSWORD },
    );
    expect(created.ok).toBe(true);
    const sessions = new SessionStore({ driver: twice.driver });
    expect((await signinAccount(twice.driver, sessions, OWNER_EMAIL, OWNER_PASSWORD)).ok).toBe(true);
    twice.close();
  });
});
