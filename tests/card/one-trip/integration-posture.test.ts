// THE INTEGRATION LANE'S RENDER-PATH MEASUREMENT (one-trip-integration
// lane, 2026-10-03): the 5 probe pages rendered through the REAL wired
// render path — render() with the config gate both OFF and ON — at the
// integration tip.
//
// DIFFERENCE FROM byte-identity.test.ts (the module lane's acceptance):
// there the harness orchestrates attach/fetch/seat manually around
// render(). HERE the gate does it (render.ts's guarded call ->
// render-gate.ts), which is what the deployed ON posture would execute.
// The pins:
//   - OFF posture trips == the wave line's numbers at this tip (fresh
//     engine, gate unset, zero one-trip machinery reachable).
//   - ON posture = the attach (once per driver connection) + the ONE data
//     round trip + the named residue.
//   - byte-identity OFF vs ON through the wired path (modulo the engine's
//     own per-render slot ids — normalizeSlotIds).
// The report lands in benchmarks/one-trip-render/integration-posture-
// report.json (machine-regenerated by the run; the receipt's terminal
// table cites it). Not a standing-net manifest member (same convention as
// the module's own tests — the net's 107 files stay 107).

import { copyFileSync, existsSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { LocalSqliteDriver } from "../../../src/server/drivers/local-sqlite.js";
import { buildOneTripClosure } from "../../../src/card/one-trip/closure-builder.js";
import {
  MIRROR_COPY_PATH,
  PROBE_PAGES,
  TripCapturingDriver,
  bootEngine,
  mirrorAvailable,
  normalizeSlotIds,
} from "./one-trip-fixture.js";
import { applyDeckDataVersionStampMigration } from "./apply-deck-data-version-stamp-migration.js";
import { scratchDir } from "../../support/scratch-dir.mjs";

const hasMirror = mirrorAvailable();
const REPORT_PATH = fileURLToPath(
  new URL("../../../benchmarks/one-trip-render/integration-posture-report.json", import.meta.url),
);

interface PostureMeasurement {
  name: string;
  offTrips: number;
  onTrips: number;
  attachTrips: number;
  dataFetchTrips: number;
  residueTrips: number;
  byteIdentical: boolean;
  offBytes: number;
  onBytes: number;
}

describe.skipIf(!hasMirror)("one-trip wired render path: OFF vs ON postures (trial-deck mirror)", () => {
  let sideDir = "";
  let sidePath = "";
  // The engine decks render through the COMPOSED engine, whose freshness
  // gate reads deck_data_version at every render entry and fails LOUDLY on
  // an unmigrated database BY DESIGN (delivery contract:79). The shared
  // mirror predates the stamp schema and is never modified, so every arm
  // renders from this migrated temp copy instead (0003, order-safe; adds no
  // render bytes).
  let stampedDeckPath = "";
  const measurements: PostureMeasurement[] = [];
  const savedEnv = { gate: process.env.DECKO_ONE_TRIP, store: process.env.DECKO_ONE_TRIP_STORE };

  beforeAll(async () => {
    const corpus = new LocalSqliteDriver({ path: MIRROR_COPY_PATH, readonly: true });
    sideDir = scratchDir("one-trip-integration-");
    sidePath = join(sideDir, "one-trip-closure-side.sqlite3");
    const side = new LocalSqliteDriver({ path: sidePath });
    await buildOneTripClosure({ corpus, side, pageNames: [...PROBE_PAGES] });
    // The stamp migration for the engine decks (see stampedDeckPath above).
    stampedDeckPath = join(sideDir, "trial-deck-stamped.sqlite3");
    copyFileSync(MIRROR_COPY_PATH, stampedDeckPath);
    const stampedLoad = new LocalSqliteDriver({ path: stampedDeckPath });
    await applyDeckDataVersionStampMigration(stampedLoad);
    stampedLoad.close();
    // The gate is process-global; this worker's env only affects this file.
    process.env.DECKO_ONE_TRIP = "1";
    process.env.DECKO_ONE_TRIP_STORE = sidePath;
  }, 180_000);

  afterAll(() => {
    if (savedEnv.gate === undefined) delete process.env.DECKO_ONE_TRIP;
    else process.env.DECKO_ONE_TRIP = savedEnv.gate;
    if (savedEnv.store === undefined) delete process.env.DECKO_ONE_TRIP_STORE;
    else process.env.DECKO_ONE_TRIP_STORE = savedEnv.store;
    try { rmSync(sideDir, { recursive: true, force: true }); } catch { /* driver holds the handle; OS temp cleans up */ }
    if (measurements.length > 0) {
      writeFileSync(REPORT_PATH, JSON.stringify({ pages: measurements }, null, 2));
    }
  });

  for (const name of PROBE_PAGES) {
    it(`renders ${name} through the wired path in both postures`, async () => {
      // --- OFF posture: gate unset, fresh engine, the wave line's path ---
      const savedGate = process.env.DECKO_ONE_TRIP;
      delete process.env.DECKO_ONE_TRIP;
      try {
        const off = new TripCapturingDriver(
          new LocalSqliteDriver({ path: stampedDeckPath, readonly: true }),
        );
        const offBoot = await bootEngine(off);
        const offHtml = await offBoot.render.render(name, "open", {});
        const offTrips = off.trips;

        // --- ON posture: gate on, fresh engine, the wired path pays
        // attach + data fetch inside render(), then the named residue ---
        process.env.DECKO_ONE_TRIP = "1"; // restore the gate for the ON arm
        const on = new TripCapturingDriver(
          new LocalSqliteDriver({ path: stampedDeckPath, readonly: true }),
        );
        const onBoot = await bootEngine(on);
        const tripsBeforeRender = on.trips;
        const stmtsBeforeRender = on.statements.length;
        const onHtml = await onBoot.render.render(name, "open", {});
        const onTrips = on.trips - tripsBeforeRender;

        // Split the ON posture's statements: attach + the one-trip fetch are
        // the wiring's own cost; everything after them is the named residue.
        let attachTrips = 0;
        let dataFetchTrips = 0;
        let statementsSeen = 0;
        for (const stmt of on.statements.slice(stmtsBeforeRender)) {
          statementsSeen++;
          if (/^ATTACH DATABASE/i.test(stmt.sql)) attachTrips++;
          else if (dataFetchTrips === 0 && /WITH RECURSIVE walk\(id\)/i.test(stmt.sql)) dataFetchTrips++;
        }
        const residueTrips = onTrips - attachTrips - dataFetchTrips;

        expect(attachTrips).toBe(1); // once per driver connection
        expect(dataFetchTrips).toBe(1); // THE one-trip law, through the gate
        expect(normalizeSlotIds(onHtml)).toBe(normalizeSlotIds(offHtml)); // the pin

        measurements.push({
          name,
          offTrips,
          onTrips,
          attachTrips,
          dataFetchTrips,
          residueTrips,
          byteIdentical: normalizeSlotIds(onHtml) === normalizeSlotIds(offHtml),
          offBytes: offHtml.length,
          onBytes: onHtml.length,
        });
      } finally {
        if (savedGate !== undefined) process.env.DECKO_ONE_TRIP = savedGate;
      }
    });
  }

  it("the OFF-posture numbers exist for every probe page (measurement completeness)", () => {
    expect(measurements.map((m) => m.name).sort()).toEqual([...PROBE_PAGES].sort());
    expect(existsSync(REPORT_PATH) || measurements.length > 0).toBe(true);
  });
});
