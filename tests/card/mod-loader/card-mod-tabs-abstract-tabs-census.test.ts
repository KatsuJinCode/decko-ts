// Abstract::Tabs — the includer census, and the hijack the census buys
// (card-mod-tabs-0.20.0 set/abstract/tabs.rb:1-88)
//
// WHAT THE PORT HOLDS AS PROSE, AND WHAT THIS FILE MAKES MECHANICAL
//
// card-mod-tabs.ts registers `abstract/tabs` as a PASSIVE basket entry —
// no views — because its `view :tabs` (abstract/tabs.rb:4-8, `cache:
// :never`) is include-scoped: only cards whose set modules run
// `include_set Abstract::Tabs` (set/inheritance.rb) reach it. That is the
// right call, and until this file the only thing holding it up was a
// comment. This file pins the three facts the call rests on, each of which
// can only fail if the decision needs re-deciding:
//
// 1. THE CENSUS IS ZERO, AND THE PINNED GEMSET SAYS SO MACHINE-CHECKABLY.
//    Measured over the pinned gemset
//    (C:/localProjects/decko-ruby-oracle-gems/ruby/3.4.0/gems, read
//    2026-10-20 while this file was written):
//
//      $ grep -rn "Abstract::Tabs" --include=*.rb --include=*.haml \
//          --include=*.yml --include=*.coffee --include=*.js .
//      (no output; exit 1)
//
//    The gemset does not even NAME the module: decko derives a set
//    module's constant from its file path, so `set/abstract/tabs.rb`
//    defines Abstract::Tabs without any line ever spelling it.
//
//    `grep -rn include_set --include=*.rb . | grep -i tab` over the same
//    tree returns exactly three lines, and all three are false friends —
//    two are `Abstract::TaskTable` (card-1.110.0 mod/core/set/self/
//    admin.rb:1 and set/type/mod.rb:4) and the third is the gem's own
//    abstract/tabs.rb:1 `include_set Abstract::BsBadge`. Not one of them
//    is an includer of Abstract::Tabs.
//
//    The restatement of that census that lives IN the repo is
//    src/card/mod-loader/set-include-graph.ts — GENERATED by
//    tools/oracle/set-include-graph.rb from this same loaded Ruby deck
//    ("for every concrete set module whose format module mixes in
//    abstract set modules (include_set, transitively)", its own header).
//    So "no concrete set module in the pinned deck reaches Abstract::Tabs"
//    is assertable from the repo with no path outside it, and that is
//    what assertion 1 below checks. A gem that later shipped an includer
//    would change that generated file, and this test would go red.
//
//    CORRECTION TO THE PORT'S OWN PROSE: card-mod-tabs.ts:49-53 claimed
//    "this gem ships no includer (the includers live in other mods, e.g.
//    card-mod-search's search types)". The first clause is right; the
//    parenthetical is FALSE against this pin — card-mod-search carries
//    no `include_set Abstract::Tabs` (assertion 1's census is the check).
//    The prose is corrected in the same commit; the decision it supported
//    does not change, and never did.
//
// 2. THE ABSTRACT :tabs IS UNREACHABLE, SO NOT REGISTERING IT COSTS
//    NOTHING. With zero includers, Ruby never puts Abstract::Tabs in any
//    card's method-resolution chain, so the abstract `view :tabs` — and
//    the whole tab_map / tab_badge / tab_title machinery behind it
//    (abstract/tabs.rb:10-88) — is dead code in stock decko 0.20.0.
//    Registering nothing is therefore EXACT parity, not a shortfall.
//
//    The oracle agrees independently, and this is not a grep restatement:
//    the gem's own oracle capture (fixtures/captured/tabs-mod-loader.json,
//    recorded via oracle-capture-tabs-mod.rb) shows every probed format
//    config false, i.e. no `_view_tabs__cache` key anywhere — the
//    abstract module's `cache: :never` setting never materialised on any
//    probed format, which is what "never included" looks like from the
//    running engine's side.
//
// 3. REGISTERING IT WOULD HIJACK EVERY CARD. This is the half that makes
//    the passive entry load-bearing rather than merely cautious. The flat
//    view table is global and last-registration-wins (mod-registrar.ts:
//    the per-set-module table walks the card's chain most-specific-first
//    and falls back to the universally-applicable all-set bucket; an
//    abstract module with no includer contributes NO chain entry, so its
//    registration can only ever land in the fallback bucket — where it
//    would sit AFTER all/tabs' own :tabs and win). Assertions 3 and 4
//    demonstrate both halves mechanically: the real manifest resolves a
//    plain card's :tabs to All::Tabs, and a scratch manifest that DOES
//    register the abstract :tabs takes that same plain card over.
//
// The fourth view family Ruby's abstract/tabs.rb reaches through
// `include_set Abstract::BsBadge` (line 1) is dead for the same reason and
// is asserted alongside assertion 1 — the whole file is unreachable, so
// nothing in it is half-ported.

import { describe, it, expect } from "vitest";

import { SET_INCLUDE_GRAPH } from "../../../src/card/mod-loader/set-include-graph.js";
import { ModLoader } from "../../../src/card/mod-loader.js";
import cardModTabs from "../../../src/card/mod-loader/mods/card-mod-tabs.js";
import type { DeckoModManifest } from "../../../src/card/mod-loader.js";

// the set-key strings this file resolves :tabs against, in the shape
// set-keys.ts emits (tests/card/mod-loader/card-mod-layout.test.ts:771-778
// walks the same two forms): "ALL" is the always-present all-set token
// (set-patterns/registry.ts:308-313), and "TYPE-rich_text" is a concrete
// cardtype's token. A plain RichText card with no left/right sets is the
// first plus its own type token.
const PLAIN_CARD_SET_KEYS = "ALL TYPE-rich_text";
const ALL_SET_KEYS = "ALL";

describe("card-mod-tabs entry 31 — the Abstract::Tabs includer census", () => {
  it("no concrete set module in the pinned deck includes Abstract::Tabs (or Abstract::BsBadge through it)", () => {
    // The generated include graph is the oracle-side census: every
    // concrete set module's transitively-included abstract modules, per
    // format, read off the loaded Ruby deck. Abstract::Tabs appearing in
    // ANY value would mean some card's chain reaches it.
    const includers: string[] = [];
    for (const [setModule, perFormat] of Object.entries(SET_INCLUDE_GRAPH)) {
      for (const [format, abstracts] of Object.entries(perFormat)) {
        for (const abstract of abstracts) {
          if (abstract === "Abstract::Tabs") includers.push(`${setModule} (${format})`);
        }
      }
    }
    expect(includers).toEqual([]);
    // ...and the graph is not vacuously empty: the census above would be
    // meaningless if the generated table had lost its abstract rows.
    // Abstract::Css is a live abstract in this deck (card-mod-style
    // set/abstract/01_css.rb, reached by Type::Css and Type::Scss), so its
    // presence proves the table still carries abstract entries — and its
    // ABSENCE of a sibling (Abstract::Tabs) is a real per-module absence,
    // not a table-wide one.
    expect(JSON.stringify(SET_INCLUDE_GRAPH)).toContain("Abstract::Css");
    expect(Object.keys(SET_INCLUDE_GRAPH).length).toBeGreaterThan(50);
  });

  it("the manifest registers abstract/tabs with NO view fns (the passive basket entry)", () => {
    const abstract = cardModTabs.setModules?.find((m) => m.setPath === "abstract/tabs");
    expect(abstract).toBeDefined();
    // every format block contributes zero views: abstract/tabs.rb's four
    // views (:tabs :4-8) are the only view declarations in the file, and
    // all of them are include-scoped, so none is registered.
    const viewCount = Object.values(abstract!.formats ?? {}).reduce(
      (n, block) => n + (block?.views?.length ?? 0),
      0,
    );
    expect(viewCount).toBe(0);

    // ...while all/tabs.rb's four ARE registered — the module Ruby gives
    // every card through the all-set bucket.
    const all = cardModTabs.setModules?.find((m) => m.setPath === "all/tabs");
    const allViews = (all!.formats?.html?.views ?? []).map((v) => v.view).sort();
    expect(allViews).toEqual(["pills", "pills_static", "tabs", "tabs_static"]);
  });

  it("a plain card's :tabs resolves to All::Tabs, never Abstract::Tabs", () => {
    const loader = new ModLoader([{ manifest: cardModTabs }]);
    loader.load();
    const chain = loader.viewChain(PLAIN_CARD_SET_KEYS, "tabs", "html");
    const owners = chain.map((entry) => entry.setModule);
    expect(owners.length).toBeGreaterThan(0);
    expect(owners).not.toContain("Abstract::Tabs");
    // the FIRST chain entry is the one the dispatcher renders (most
    // specific first), and it is the all-set module Ruby's method lookup
    // reaches for a card with no includer.
    expect(owners[0]).toBe("All::Tabs");
    loader.reset();
  });

  it("COUNTER-PROOF: even a stray abstract :tabs registration cannot reach a card (the abstract-kind guard)", () => {
    // The scratch manifest is the real one plus the abstract registration
    // the port deliberately withholds. It exists only to measure what a
    // stray registration would do; nothing ships it.
    //
    // The FIRST draft of this assertion assumed the stray registration
    // would hijack every card through the flat last-wins table. It does
    // not, and the reason is worth more than the assumption:
    // mod-loader.ts:377-393 gates flat registration on the module's KIND
    // — an all-set's format module goes to Set.modules[:base_format] and
    // is mixed into the BASE format class every card inherits, so ONLY
    // base-kind views belong on the flat record. `abstract/*` is not
    // base-kind, so its views never reach it (the guard's own named
    // test is tests/card/mod-loader/view-set-scope-fallback.test.ts; the
    // harm it prevents is set/right/html_message's :content replacing the
    // engine's main content renderer deck-wide).
    //
    // So the passive entry is protected by TWO independent mechanisms, and
    // this file measures both: the kind guard (below, on a card) and the
    // census above (no card's chain could reach the abstract bucket
    // anyway). The census is the one that matters long-term — the kind
    // guard is a property of the loader, the census is a property of the
    // pinned gemset, and only the second tells you the Ruby side is dead.
    const hijackView = () => "ABSTRACT_TABS_HIJACK";
    const hijacking: DeckoModManifest = {
      ...cardModTabs,
      setModules: cardModTabs.setModules?.map((m) =>
        m.setPath === "abstract/tabs"
          ? {
              ...m,
              formats: {
                html: { views: [{ view: "tabs", viewFn: hijackView }] },
              },
            }
          : m,
      ),
    };
    const loader = new ModLoader([{ manifest: hijacking }]);
    loader.load();

    // (a) a concrete card's chain is unchanged: still All::Tabs.
    for (const keys of [PLAIN_CARD_SET_KEYS, ALL_SET_KEYS]) {
      const owners = loader.viewChain(keys, "tabs", "html").map((e) => e.setModule);
      expect(owners).not.toContain("Abstract::Tabs");
      expect(owners[0]).toBe("All::Tabs");
    }

    // (b) the registration IS recorded, and the one place it is visible is
    // the EMPTY-setKeys abstract-pseudo-pattern arm — the probe the
    // loader runs for abstract modules (mod-loader.ts's chain fallback;
    // its callers are the abstract probes in card-mod-content.test.ts,
    // default-mod-deck.test.ts and view-dispatch-superview.test.ts, all
    // passing "" by hand). That arm is not a card render, which is exactly
    // why a stray abstract registration is inert in production.
    const emptyChain = loader.viewChain("", "tabs", "html").map((e) => e.setModule);
    expect(emptyChain).toContain("Abstract::Tabs");
    // and it sorts after the all-set module there too — so even the probe
    // arm resolves to All::Tabs first.
    expect(emptyChain[0]).toBe("All::Tabs");
    loader.reset();
  });
});
