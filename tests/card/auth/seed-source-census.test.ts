// card-mod-defaults (register entry 12): the seed-SOURCE census.
//
// WHAT THIS CONVERTS
// The register graded card-mod-defaults PARTIAL on one claim: "the
// 604-row standard seed corpus is carried by no port surface (grep over
// src/ found no defaults-fixture consumer)". That claim is TRUE and it
// understates the shape of the problem by one step.
//
// The sharper finding, measured: boot-seed.ts cites Ruby's rule
// (seed.rb:62, `Mod.fetch(seed_mods[index]).subpath "data", "fixtures",
// env`) and then resolves a DIFFERENT INDEX than Ruby does. Ruby calls it
// with index 0 (seed.rb:8-9) and seed_mods[0] is `defaults` - pushed
// there by the gem's own `unshift`. boot-seed.ts transcribes index 1,
// mod/core's eleven-row corpus. So it is not a different transcription
// of one corpus; it is a different corpus.
//
// This file pins the ordering, the resolution rule, both corpora's row
// counts, and the divergence itself - from inside the repo, so a future
// change to the corpus choice is a value flip (PORT_SEED_SOURCE) that
// this test reports rather than a fact buried in two files' prose.
//
// WHY IT IS CHECKABLE WITHOUT THE GEMSET: src/card/auth/
// seed-corpus-census.ts is GENERATED by tools/oracle/seed-corpus-census.rb
// from the pinned gemset, the same arrangement as
// src/card/mod-loader/set-include-graph.ts. The census asserts against
// that generated table; the generator's own derivation is quoted in the
// commit and re-runnable.
//
// WHAT THIS DOES NOT DO: it does not land the 604-row corpus. That is
// Decko's standard sample deck; seeding it into every fresh port deck is
// a product call (what every demo and deployment CONTAINS), not a parity
// fix, and it is named as SKIPPED_CORPUS with its unblock.

import { describe, expect, it } from "vitest";
import {
  DEFAULT_PATH_INDEX,
  DEFAULT_PATH_SOURCE,
  PORT_SEED_SOURCE,
  RUBY_SEED_MODS_FIRST,
  SEED_MODS_FIRST_CONSUMERS,
  SEED_MODS_ORDER,
  SEED_TYPE,
  SKIPPED_CORPUS,
  rubyDefaultSeedSource,
  rubySeedSource,
  seedSourceComparison,
} from "../../../src/card/auth/seed-source.js";
import { readFileSync } from "node:fs";

describe("seed-source census (card-mod-defaults, register entry 12)", () => {
  it("the railtie's order is NOT the seed order, and the gem is what moves it", () => {
    // railtie.rb:6 assigns [:core]. card-mod-defaults unshifts :defaults.
    // The census carries BOTH so the diff is readable as data.
    const census = readFileSync("src/card/auth/seed-corpus-census.ts", "utf8");
    expect(census).toContain('RAILTIE_BASE_SEED_MODS_ORDER: readonly string[] = ["core"]');
    expect(SEED_MODS_ORDER).toEqual(["defaults", "core"]);
    // Exactly ONE mutation in the whole pin, and it is this gem's line.
    expect(census).toContain("card-mod-defaults-0.20.0/lib/card/mod/defaults.rb");
    expect(census).toContain('op: "unshift"');
    // seed_type is the railtie's :real; the test env is the one override
    // (config/environments/test.rb:6).
    expect(SEED_TYPE).toBe("real");
  });

  it("default_path is index 0, and index 0 is the 604-row defaults corpus", () => {
    expect(DEFAULT_PATH_INDEX).toBe(0);
    expect(DEFAULT_PATH_SOURCE).toBe("defaults");
    const ruby = rubyDefaultSeedSource();
    expect(ruby).not.toBeNull();
    expect(ruby!.gem).toBe("card-mod-defaults-0.20.0");
    expect(ruby!.fixtureDir).toBe("data/fixtures/real");
    // The register's own number, checked against the generated census.
    expect(ruby!.tables.cards).toBe(604);
    expect(ruby!.tables.card_actions).toBe(599);
    expect(ruby!.tables.card_acts).toBe(1);
    expect(ruby!.tables.card_references).toBe(519);
    // card_changes is 0 in both real corpora - the table exists, it is
    // simply empty, so "not ported" would be the wrong word for it.
    expect(ruby!.tables.card_changes).toBe(0);
  });

  it("index 1 is core's ELEVEN-row corpus - the one the port transcribes", () => {
    // This is the number that makes the divergence legible: the two
    // corpora are not two views of one dataset.
    const core = rubySeedSource("real", 1);
    expect(core).not.toBeNull();
    expect(core!.gem).toBe("core");
    expect(core!.tables.cards).toBe(11);
    expect(core!.tables.card_actions).toBe(11);
    expect(core!.tables.card_references).toBe(1);
    expect(PORT_SEED_SOURCE).toEqual({ env: "real", index: 1 });
  });

  it("THE DIVERGENCE: the port seeds a different corpus than Ruby does", () => {
    const cmp = seedSourceComparison();
    expect(cmp.sameCorpus).toBe(false);
    expect(cmp.ruby).toEqual({ mod: "defaults", cards: 604 });
    expect(cmp.port).toEqual({ mod: "core", cards: 11 });
    // Same rule, different index - the comparison is the whole finding.
    expect(cmp.port!.cards).toBeLessThan(cmp.ruby!.cards);
  });

  it("the corpus is a NAMED SKIP with its unblock, not a vague deferral", () => {
    expect(SKIPPED_CORPUS.mod).toBe("defaults");
    expect(SKIPPED_CORPUS.index).toBe(0);
    expect(SKIPPED_CORPUS.cards).toBe(604);
    expect(SKIPPED_CORPUS.reason).toMatch(/product call/i);
    // The unblock has to be actionable, not aspirational.
    expect(SKIPPED_CORPUS.unblock).toContain("PORT_SEED_SOURCE.index");
    expect(SKIPPED_CORPUS.unblock).toContain("DEFAULT_PATH_INDEX");
    expect(SKIPPED_CORPUS.unblock).toContain("card-mod-defaults-0.20.0/data/fixtures/real");
  });

  it("seed_mods.first reaches the asset-output path too, not just the seed path", () => {
    // Second-order consequence of the same one line: the defaults gem's
    // unshift is also the argument card-mod-script and card-mod-style
    // pass to `super(...)` when building a coded asset output.
    expect(RUBY_SEED_MODS_FIRST).toBe("defaults");
    const files = SEED_MODS_FIRST_CONSUMERS.map((c) => c.file);
    expect(files).toContain("card-mod-script-0.20.0/set/type_plus_right/set/script.rb");
    expect(files).toContain("card-mod-style-0.20.0/set/type_plus_right/set/style.rb");
    for (const c of SEED_MODS_FIRST_CONSUMERS) {
      expect(c.text).toContain("seed_mods.first");
    }
  });

  it("a corpus that is absent on disk resolves to null, not to an empty one", () => {
    // core ships no data/fixtures/test/ (measured: the directory does not
    // exist). `Mod.fetch(...)` names a mod; a mod with no corpus there
    // has none, and the resolver must say so rather than return an empty
    // table map that would read as "a corpus with zero rows" - the same
    // null-vs-empty confusion this house's deletion-safety rule is about.
    expect(rubySeedSource("test", 1)).toBeNull();
    expect(rubySeedSource("real", 99)).toBeNull();
    // ...and the census emits `null` for the absent directory rather than
    // an empty map. This assertion FAILED on the first run: the generator
    // emitted `tables: {}` and the resolver then handed a caller a corpus
    // that does not exist. The fix was in the generator, not the
    // assertion.
    const census = readFileSync("src/card/auth/seed-corpus-census.ts", "utf8");
    expect(census).toMatch(/mod: "core"[\s\S]*?test: null,/);
    // The present corpus next to it is still a full object, so the null
    // is discriminating rather than blanket.
    expect(census).toMatch(/mod: "core"[\s\S]*?real: \{[\s\S]*?cards: 11,/);
  });

  it("the generator re-derives the order from source, it is not hardcoded", async () => {
    // Guard against the census becoming an unfalsifiable constant: the
    // generator reads the railtie assignment and the gem mutations off
    // disk. If it ever hardcoded ["defaults","core"], the two strings it
    // greps for would stop being load-bearing.
    const gen = await import("node:fs/promises");
    const src = await gen.readFile("tools/oracle/seed-corpus-census.rb", "utf8");
    expect(src).toMatch(/config\\?\.seed_mods\\s\*=\\s\*\\\[/);
    expect(src).toContain("seed_mods\\.unshift");
    expect(src).toContain("db_path".replace("db_path", "default_path"));
    // and it must not name the answer as a literal order
    expect(src).not.toContain('"seed_mods_order" => ["defaults", "core"]');
  });
});