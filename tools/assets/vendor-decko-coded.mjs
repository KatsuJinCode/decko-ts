// Read only an explicitly supplied local card-mod-carrierwave-0.20.0 source.
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import path from "node:path";
const gem = process.argv[2];
if (!gem || !path.isAbsolute(gem) || path.basename(gem) !== "card-mod-carrierwave-0.20.0") throw new Error("supply the absolute carrierwave0.20.0 gem directory");
const assets = {}, files = [];
for (const [codename, extension, variants] of [
  ["logo", "svg", ["original"]], ["decko_logo", "svg", ["original"]],
  ["favicon", "png", ["original", "icon", "small", "medium", "large"]],
]) {
  const identifier = `:${codename}/carrierwave.${extension}`;
  const versions = {};
  for (const variant of variants) {
    const relative = `data/files/${codename}/image-${variant}.${extension}`;
    const bytes = readFileSync(path.join(gem, relative));
    const sha256 = createHash("sha256").update(bytes).digest("hex");
    if (extension === "svg" && sha256 !== "312389d4825c90b0b9fe27969b333b83169e4328504115d21f2db7f04172f230") throw new Error("stock logo differs from the already vendored source");
    versions[variant] = { base64: bytes.toString("base64"), sha256 };
    files.push({ path: relative, bytes: bytes.length, sha256 });
  }
  assets[identifier] = { codename, extension, versions };
}
const root = new URL("../../vendor/decko-coded-attachments/", import.meta.url);
mkdirSync(root, { recursive: true });
writeFileSync(new URL("assets.js", root), `// Exact stock Decko gem bytes, generated by tools/assets/vendor-decko-coded.mjs.\nexport const assets = ${JSON.stringify(assets)};\n`);
writeFileSync(new URL("assets.d.ts", root), "export const assets: Readonly<Record<string, {codename: string; extension: string; versions: Readonly<Record<string, {base64: string; sha256: string}>>}>>;\n");
writeFileSync(new URL("provenance.json", root), JSON.stringify({ gem: "card-mod-carrierwave", version: "0.20.0", license: "GPL-3.0-or-later", files }, null, 2) + "\n");
console.log(JSON.stringify({ files: files.length, bytes: files.reduce((n, file) => n + file.bytes, 0) }));
