// tools/bundle-cold-render-point-query-callers.mjs — build the
// point-query CALL-SITE census into a plain-ESM file node runs directly.
//
// WHY A BUILD STEP: the census imports the engine from TypeScript sources
// and the repo has no tsx/ts-node. esbuild is already the bundler for the
// deployable artifact, so the same one is used here — same sources, no
// second toolchain. Same shape as
// tools/bundle-cold-render-fetch-shape-instrument.mjs.
//
//   node tools/bundle-cold-render-point-query-callers.mjs
//   node benchmarks/cold-render/measure-point-query-callers.mjs --names Laundry
//
// Output: benchmarks/cold-render/measure-point-query-callers.mjs
// node: builtins stay external (the census only uses node:fs).

import { build } from "esbuild";
import { mkdirSync } from "node:fs";
import { builtinModules } from "node:module";
import { resolve } from "node:path";

const here = resolve(process.cwd());
const out = resolve(here, "benchmarks/cold-render/measure-point-query-callers.mjs");
mkdirSync(resolve(here, "benchmarks/cold-render"), { recursive: true });

const builtins = new Set([...builtinModules, ...builtinModules.map((n) => `node:${n}`)]);

await build({
  entryPoints: [
    resolve(here, "benchmarks/cold-render/instrument-cold-render-point-query-callers.ts"),
  ],
  outfile: out,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  // keepNames so the stack frames the census attributes still carry their
  // original function names in a diagnostic run.
  keepNames: true,
  // better-sqlite3 is a CommonJS native addon: it reaches node:fs and
  // node:path through require(), which esbuild's ESM output cannot do. It
  // is marked external and loaded lazily by the instrument only on the
  // --driver local path, so the wire run never pays for it.
  external: [...builtins, "sass", "coffeescript", "better-sqlite3"],
  banner: {
    js: "// GENERATED by tools/bundle-cold-render-point-query-callers.mjs — edit the .ts source, not this file.",
  },
  logLevel: "warning",
});

console.log(`bundled ${out}`);
