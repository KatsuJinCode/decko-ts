# The defaults SEED CORPUS generator: transcribe card-mod-defaults-0.20.0's
# data/fixtures/real/*.yml (the corpus a fresh Ruby deck seeds, seed_mods[0])
# into the port's committed seed asset
# deploy/seed/defaults-seed-corpus.json.
#
# Why a generator and not hand transcription: register row 12's close lands
# the corpus the census had only counted - 604 cards plus the corpus's own
# action/act/reference rows (Cardio::Seed.load's FixtureSet.create_fixtures
# loads Cardio::Seed::TABLES, seed.rb:4-5 + :20-22 - direct rows, no card
# saves). The rows are DATA off the pinned gem; the generator is the
# reproducible path from the pin to the committed asset, the same shape as
# seed-corpus-census.rb for the counts this corpus now makes real.
#
# WHY AN ASSET AND NOT A COMPILED MODULE: the corpus rode the engine graph
# as src/card/auth/defaults-seed-corpus.ts through boot-seed.ts's import,
# and the v21 roll's engine bundle crossed the boot-safe budget because of
# it (7,626,797 output bytes against the 7,600,000 budget;
# tools/vendor/edge-bundle-budget.mjs, decision 0009: the bundle stays
# monolithic and the budget is the real margin). The corpus is boot-time
# DATA: the JSON asset below is read at seed time by the boot that opens
# the deck (vm-staging-server.mjs, through
# src/card/auth/defaults-seed-corpus-asset.ts's loader) and injected into
# bootstrapFreshDeck - the engine imports none of it, and the bundle
# carries none of it.
#
# The two Ruby migration tables (schema_migrations, transform_migrations)
# are NOT transcribed: their rows record the RUBY SCHEMA's applied-migration
# versions, and the port's schema carries its own migration ledger - seeding
# Ruby's versions into it would mark the port's own migrations applied
# without ever running them. That boundary is named in boot-seed.ts.
#
# Run: ruby tools/oracle/defaults-seed-corpus.rb [<gems-dir>]
#   gems-dir defaults to the pinned gemset path. Writes the JSON asset and
#   prints the row counts it emitted. Aborts when the counts disagree with
#   the committed census (seed-corpus-census.ts): a corpus that grew or
#   shrank is a DIFFERENT corpus and must be re-decided, not silently
#   re-landed.

require "json"
require "yaml"

GEMS_DIR = ARGV[0] || "C:/localProjects/decko-ruby-oracle-gems/ruby/3.4.0/gems"
MOD = "card-mod-defaults-0.20.0"
FIXTURE_DIR = File.join(GEMS_DIR, MOD, "data", "fixtures", "real")
OUT = File.join(__dir__, "..", "..", "deploy", "seed", "defaults-seed-corpus.json")

# The census's committed counts for this corpus (seed-corpus-census.ts,
# generated by seed-corpus-census.rb over the same pinned gemset). The
# generator refuses to emit a corpus whose counts drifted.
EXPECTED = { "cards" => 604, "card_actions" => 599, "card_acts" => 1,
             "card_changes" => 0, "card_references" => 519 }.freeze

# The tables Cardio::Seed::TABLES loads (seed.rb:4-5) minus the two Ruby
# migration ledgers named in the header.
TABLES = %w[cards card_actions card_acts card_changes card_references].freeze

# Fixture-stamp to the port's sqlDateTime shape: UTC "YYYY-MM-DD HH:MM:SS",
# sub-second precision dropped when it is zero (every fixture stamp is).
def sql_time(value)
  return nil if value.nil?
  t = value.is_a?(Time) ? value.utc : Time.parse(value.to_s)
  base = format("%04d-%02d-%02d %02d:%02d:%02d", t.year, t.month, t.day, t.hour, t.min, t.sec)
  frac = t.nsec
  frac.zero? ? base : format("%s.%03d000", base, frac / 1_000_000)
end

def cell(value)
  case value
  when nil then nil
  when Time, Date, DateTime then sql_time(value)
  when String then value
  when Integer then value
  else value.to_s
  end
end

def rows_of(table)
  path = File.join(FIXTURE_DIR, "#{table}.yml")
  data = YAML.safe_load(File.read(path), permitted_classes: [Time, Date, DateTime])
  abort "no #{table} rows in #{path}" if data.nil? || data.empty? && EXPECTED[table].nonzero?
  data.values.sort_by { |row| row["id"] || 0 }
end

corpus = {}
TABLES.each do |table|
  rows = rows_of(table)
  count = rows.size
  expected = EXPECTED[table]
  if count != expected
    abort "#{table}: the pinned corpus holds #{count} rows, the census says #{expected} - " \
          "a different corpus than the one the register measured; re-decide before re-landing"
  end
  corpus[table] = rows
end

cards = corpus["cards"].map do |r|
  {
    id: r["id"], name: r["name"], key: r["key"], codename: r["codename"],
    leftId: r["left_id"], rightId: r["right_id"],
    createdAt: sql_time(r["created_at"]), updatedAt: sql_time(r["updated_at"]),
    creatorId: r["creator_id"], updaterId: r["updater_id"],
    readRuleClass: r["read_rule_class"], readRuleId: r["read_rule_id"],
    trash: r["trash"], typeId: r["type_id"], dbContent: r["db_content"],
  }
end
actions = corpus["card_actions"].map do |r|
  { id: r["id"], cardId: r["card_id"], cardActId: r["card_act_id"],
    superActionId: r["super_action_id"], actionType: r["action_type"], draft: r["draft"] }
end
acts = corpus["card_acts"].map do |r|
  { id: r["id"], cardId: r["card_id"], actorId: r["actor_id"],
    actedAt: sql_time(r["acted_at"]), ipAddress: r["ip_address"] }
end
changes = corpus["card_changes"].map do |r|
  { id: r["id"], cardActionId: r["card_action_id"], field: r["field"], value: r["value"] }
end
references = corpus["card_references"].map do |r|
  { id: r["id"], refererId: r["referer_id"], refereeKey: r["referee_key"],
    refereeId: r["referee_id"], refType: r["ref_type"], isPresent: r["is_present"] }
end

asset = {
  "source" => "#{MOD}/data/fixtures/real",
  "generator" => "tools/oracle/defaults-seed-corpus.rb",
  "seedModsIndex" => 0,
  "env" => "real",
  "rowNote" =>
    "Column names are the port's camelCase; nil columns ride as null. " \
    "Junction rows carry sides only - the fixture's own convention, the " \
    "one the core fixture's rows 10/11 use too; the engine composes their " \
    "names from the sides. Timestamps are the port's sqlDateTime shape " \
    "(UTC, sub-second precision dropped when zero).",
  "tables" => {
    "cards" => cards,
    "card_actions" => actions,
    "card_acts" => acts,
    "card_changes" => changes,
    "card_references" => references,
  },
}

File.write(OUT, JSON.pretty_generate(asset) << "\n")
puts "wrote #{OUT}"
puts TABLES.map { |t| "#{t}=#{corpus[t].size}" }.join(" ")
