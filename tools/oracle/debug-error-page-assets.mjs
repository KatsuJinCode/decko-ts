// tools/oracle/debug-error-page-assets.mjs - regenerate
// src/card/render/debug-server-error-assets.ts from the installed
// card-mod-format gem's set/all/html/debug_server_error.haml (the template
// BetterErrors' error page is rendered through in Ruby). The template's
// :css filter and its three :javascript filters are static text; this copies
// them verbatim (the bodies as the template indents them) so the port's
// debug_server_error view carries the same stylesheet and scripts.
//
//   node tools/oracle/debug-error-page-assets.mjs [path/to/debug_server_error.haml]
import { readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] ??
  "C:/Ruby33-x64/lib/ruby/gems/3.3.0/gems/card-mod-format-0.20.0/set/all/html/debug_server_error.haml";
const lines = readFileSync(src, "utf8").split(/\r?\n/);

// Top-level blocks start at column 0; filter bodies are the indented lines
// that follow ":css" / ":javascript".
const blocks = [];
let current;
for (const line of lines) {
  if (/^\S/.test(line)) {
    current = { head: line, body: [] };
    blocks.push(current);
  } else if (current !== undefined) {
    current.body.push(line);
  }
}
const filterBody = (b) => {
  const body = [...b.body];
  while (body.length > 0 && body[body.length - 1].trim() === "") body.pop();
  return body.join("\n");
};
const css = blocks.filter((b) => b.head === ":css").map(filterBody);
const js = blocks.filter((b) => b.head === ":javascript").map(filterBody);
if (css.length !== 1 || js.length !== 3) {
  throw new Error(`unexpected template shape: ${css.length} css, ${js.length} javascript filters`);
}
if (!js[2].includes('var OID = "#{id}";')) throw new Error("the frame script no longer interpolates #{id}");

const out = `// GENERATED by tools/oracle/debug-error-page-assets.mjs from
// card-mod-format-0.20.0 set/all/html/debug_server_error.haml: the
// template's static :css and :javascript filter bodies. Regenerate with the
// script; do not edit.

/** The :css filter body. */
export const DEBUG_ERROR_PAGE_CSS = ${JSON.stringify(css[0])};

/** The two leading :javascript filters (element shim, Turbolinks guard). */
export const DEBUG_ERROR_PAGE_HEAD_SCRIPTS: readonly string[] = ${JSON.stringify(js.slice(0, 2), null, 2)};

/** The frame-navigation :javascript filter; "#{id}" is the error page id. */
export const DEBUG_ERROR_PAGE_FRAME_SCRIPT = ${JSON.stringify(js[2])};
`;
const target = resolve(here, "../../src/card/render/debug-server-error-assets.ts");
writeFileSync(target, out);
console.log(`wrote ${target}`);
