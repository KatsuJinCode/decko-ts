#!/usr/bin/env node
// treewalk-family-row-receipt.mjs - the [Family] lane's row receipt.
//
// WHAT THIS IS. The lane's job is to work the family's thirty WORKING
// rows in row-id order and close a row to DONE only where the port
// measurably matches the pinned Ruby. This script writes the RECEIPT for
// the whole family: one line per row, with the row's measured
// dispositions, the defs the port does not carry, and the row's verdict.
//
// The receipt is generated from the rig's own output, so it cannot
// disagree with the instrument. It is a READING, and the verdict on each
// row follows one rule:
//
//   DONE     the row's defs are all PORTED, PORTED-INLINE,
//            NAMED-COLLAPSE or SKIP. There is no def the port does not
//            carry, so the port matches the pinned Ruby on this row's
//            whole surface.
//   WORKING  the row has at least one GAP: a def the port does not
//            carry, and the reason is named.
//
// WHY THE RECEIPT NAMES EVERY GAP DEF AND NOT A COUNT. A count is a
// number a reader cannot check. A def name, its Ruby file and line, and
// whether the port mentions it at all is three facts a reader can check
// against the pinned gemset and the port tree in a minute.
//
// Run:
//   node tools/treewalk-family-row-receipt.mjs
//   node tools/treewalk-family-row-receipt.mjs --out <path>

import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '..');

const DISPOSITION_TOOL = join(HERE, 'treewalk-family-row-disposition.mjs');
const ROSTER = process.env.DECKO_COMPLETENESS_ROSTER
  ?? 'C:/localProjects/brandonDojoTech/docs/registry/completeness-roster.json';
const FAMILY = process.env.DECKO_TREEWALK_FAMILY ?? 'register-treewalk';

const outIndex = process.argv.indexOf('--out');
const OUT = outIndex >= 0 ? process.argv[outIndex + 1] : null;

const roster = JSON.parse(readFileSync(ROSTER, 'utf8'));
const working = roster.items
  .filter((i) => i.family === FAMILY && i.bucket === 'WORKING ON IT')
  .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const raw = execFileSync(process.execPath, [DISPOSITION_TOOL, '--all', '--json'], {
  encoding: 'utf8',
  maxBuffer: 256 * 1024 * 1024,
});
const measured = JSON.parse(raw);
const byId = new Map(measured.map((r) => [r.id, r]));

const lines = [];
lines.push(`# The ${FAMILY} family's working rows, measured`);
lines.push('');
lines.push(`Generated by \`tools/treewalk-family-row-receipt.mjs\` from the rig's own output`);
lines.push('(`tools/treewalk-family-row-disposition.mjs`), so the receipt cannot disagree with');
lines.push('the instrument.');
lines.push('');
lines.push('The pinned gemset is the deck at');
lines.push('`C:/localProjects/decko-ruby-oracle-gems/ruby/3.4.0/gems`; the port tree is this');
lines.push("checkout's `src/`.");
lines.push('');
lines.push('## What a verdict means');
lines.push('');
lines.push('- **DONE** - every `def` in the row\'s Ruby file set is PORTED (the port binds');
lines.push('  the behaviour), PORTED-INLINE (the port carries it at a call site and cites');
lines.push('  this row\'s Ruby source), NAMED-COLLAPSE (the port\'s own words say it carries');
lines.push('  the behaviour by a different mechanism) or SKIP (a private helper the pinned');
lines.push('  deck cannot reach). There is no `def` the port does not carry, so the port');
lines.push('  matches the pinned Ruby on this row\'s whole surface.');
lines.push('- **WORKING** - the row has at least one GAP: a `def` the port does not carry.');
lines.push('  The gap is named below, with the def, its Ruby file and line, and whether');
lines.push('  the port mentions the name at all.');
lines.push('');
lines.push('A def is a GAP when the port neither binds it, nor carries it at a citing');
lines.push('call site, nor names a collapse of it - AND the pinned deck can reach it, or');
lines.push('it is PUBLIC. A public method the deck never calls is still API.');
lines.push('');

let done = 0;
const workingRows = [];
for (const item of working) {
  const m = byId.get(item.id);
  if (!m) continue;
  const c = m.counts;
  const gaps = m.gaps;
  const verdict = gaps.length === 0 ? 'DONE' : 'WORKING';
  if (verdict === 'DONE') done++;
  else workingRows.push({ item, m, gaps });
  lines.push(`## ${item.id} - ${verdict}`);
  lines.push('');
  lines.push(`- Ruby: \`${item.sourceParent}\``);
  lines.push(`- The row's own label: ${item.label}`);
  lines.push(`- ${m.rubyFiles} Ruby file(s), ${m.defCount} def(s).`);
  lines.push(
    `- PORTED ${c.PORTED ?? 0} / PORTED-INLINE ${c['PORTED-INLINE'] ?? 0} / `
    + `NAMED-COLLAPSE ${c['NAMED-COLLAPSE'] ?? 0} / SKIP ${c.SKIP ?? 0} / GAP ${c.GAP ?? 0}.`,
  );
  if (gaps.length > 0) {
    lines.push('');
    lines.push('The defs the port does not carry:');
    lines.push('');
    lines.push('| def | Ruby | visibility | the pinned deck reaches it | the port mentions the name |');
    lines.push('| --- | --- | --- | --- | --- |');
    for (const g of gaps) {
      const leaf = g.file.split('/').pop();
      lines.push(
        `| \`${g.name}\` | ${leaf}:${g.line} | ${g.visibility ?? '?'} `
        + `| ${g.reachability ?? '?'} | ${g.portMention ?? 'no'} |`,
      );
    }
  }
  lines.push('');
}

lines.push('## The family, in row-id order');
lines.push('');
lines.push('| row | defs | PORTED | INLINE | COLLAPSE | SKIP | GAP | verdict |');
lines.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
for (const item of working) {
  const m = byId.get(item.id);
  if (!m) continue;
  const c = m.counts;
  lines.push(
    `| ${item.id} | ${m.defCount} | ${c.PORTED ?? 0} | ${c['PORTED-INLINE'] ?? 0} `
    + `| ${c['NAMED-COLLAPSE'] ?? 0} | ${c.SKIP ?? 0} | ${c.GAP ?? 0} `
    + `| ${m.gaps.length === 0 ? 'DONE' : 'WORKING'} |`,
  );
}
lines.push('');
lines.push(`**${done} of ${working.length} rows measure with no gap.**`);
lines.push('');

const text = lines.join('\n');
if (OUT) {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT}`);
} else {
  console.log(text);
}
