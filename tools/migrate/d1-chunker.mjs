// d1-chunker.mjs — emit chunked D1-ready INSERT files from any row source.
//
// The M5 productized importer (tools/migrate/import-deck.mjs) splits a real
// deck's hundreds-of-MB INSERT stream into small chunk files that
// `wrangler d1 execute --local --file <chunk>` can swallow one at a time.
// D1's per-execute statement-count limit (the empirical ceiling is the
// number this module lets the caller discover; the default of 1000 rows
// per chunk is the conservative starting point) and per-statement size
// cap (~100 KB after normalization) make a single wrangler --file call
// unsafe for production-sized decks.
//
// Each chunk is a self-contained .sql file:
//   - a header comment naming the chunk and the table set it covers,
//   - a `BEGIN` / `COMMIT` pair wrapping the INSERTs (D1 honors transactions,
//     and one commit per chunk keeps the WAL trim),
//   - one INSERT per row, in the TARGET DDL column order,
//   - a single `;` terminator per statement.
//
// Rows arrive as { table, values, columns } - the same shape every other
// importer module already produces. The chunker routes them through the
// existing schema-map.mjs machinery for column drift handling
// (`content` -> `db_content`, NULL-fill missing source columns, etc.)
// before emitting.
//
// The output is deterministic: same source -> same chunked files
// (statement order matches the source's iteration order, which the
// importers themselves guarantee via keyset pagination).

import { mkdirSync, createWriteStream } from "node:fs";
import { join } from "node:path";
import { mapRowToTarget } from "./schema-map.mjs";
import { parseTargetSchema } from "./import.mjs";

/** SQL-quote a value for an INSERT literal body. NULL -> NULL, numbers
 *  rendered via JS String (which is sufficient for SQLite), strings get
 *  the doubled-single-quote escape. */
export function quoteValue(v) {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") {
    if (!Number.isFinite(v)) throw new Error(`non-finite number ${v} in seed row`);
    return String(v);
  }
  if (typeof v === "string") {
    return `'${v.replace(/'/g, "''")}'`;
  }
  if (v instanceof Uint8Array) {
    return `X'${Buffer.from(v).toString("hex")}'`;
  }
  if (typeof v === "boolean") return v ? "1" : "0";
  // Anything else (BigInt, etc.) - stringify carefully.
  return `'${String(v).replace(/'/g, "''")}'`;
}

/** Format one row into a D1-ready INSERT statement in target DDL order.
 *  Returns the SQL string and the row's bytes (best-effort: JS string
 *  length in UTF-16 code units). */
export function rowToInsert(targetColumns, values) {
  const cols = targetColumns.map((c) => `"${c}"`).join(", ");
  const vals = values.map(quoteValue).join(", ");
  return `INSERT INTO "TARGET_TABLE_PLACEHOLDER" (${cols}) VALUES (${vals});`;
}

/** Produce one chunk's SQL file as a string. The caller passes the chunk
 *  number, a list of { table, values } tuples (already mapped to the
 *  target DDL), and the tableColumns map (table -> [colName, ...]).
 *  Rows are grouped by table to keep each chunk's statement set
 *  contiguous; the chunk emits one BEGIN/COMMIT pair around all rows. */
export function renderChunk({
  chunkNumber,
  chunksTotal,
  rowStart,
  rowEnd,
  tableColumns,
  rows,
  includePragmas = true,
}) {
  const header = [
    `-- generated by tools/migrate/import-deck.mjs`,
    `-- chunk ${chunkNumber} of ${chunksTotal} (rows ${rowStart}..${rowEnd}, ${rows.length} statements)`,
    `-- DO NOT EDIT - regenerate with the import-deck CLI`,
    "",
  ];
  const pragmas = includePragmas ? ["PRAGMA defer_foreign_keys = ON;", "BEGIN TRANSACTION;", ""] : [];
  const footer = includePragmas ? ["", "COMMIT;", "PRAGMA defer_foreign_keys = OFF;", ""] : [];
  const body = [];
  let lastTable = undefined;
  for (const row of rows) {
    const cols = tableColumns[row.table];
    if (cols === undefined) {
      throw new Error(`renderChunk: no target DDL columns for source table "${row.table}"`);
    }
    if (row.table !== lastTable) {
      if (body.length > 0) body.push("");
      body.push(`-- table: ${row.table}`);
      lastTable = row.table;
    }
    const insert = rowToInsert(cols, row.values).replace(
      "TARGET_TABLE_PLACEHOLDER",
      row.table,
    );
    body.push(insert);
  }
  return header.join("\n") + pragmas.join("\n") + body.join("\n") + "\n" + footer.join("\n");
}

/** Stream-emit chunked SQL files. The caller drives iteration over the
 *  source rows (an async generator) and the chunker assembles chunks up
 *  to `maxRows` statements or `maxBytes` SQL bytes (whichever hits first).
 *  Returns the chunk manifest: [{ file, rows, bytes, tables }, ...].
 *
 *  opts:
 *    rows:        async iterable of { table, columns, values } source rows
 *    tableColumns: table -> [colName, ...] target DDL columns
 *    outDir:      directory to write chunk-NNN.sql files into
 *    maxRows:     max INSERT statements per chunk (default 1000)
 *    maxBytes:    max SQL bytes per chunk (default 8 MiB)
 *    onProgress?: (chunksWritten, totalRowsSeen) callback
 */
export async function writeChunkedSeed(opts) {
  const {
    rows,
    tableColumns,
    outDir,
    maxRows = 1000,
    maxBytes = 8 * 1024 * 1024,
    onProgress,
  } = opts;
  mkdirSync(outDir, { recursive: true });
  const chunks = [];
  let buffer = [];
  let bufferBytes = 0;
  let totalRows = 0;
  let chunkNumber = 0;
  let rowStart = 1;

  const flush = async () => {
    if (buffer.length === 0) return;
    chunkNumber += 1;
    const rowEnd = totalRows;
    const sql = renderChunk({
      chunkNumber,
      chunksTotal: 0, // patched at the end
      rowStart,
      rowEnd,
      tableColumns,
      rows: buffer,
    });
    const padded = String(chunkNumber).padStart(4, "0");
    const file = join(outDir, `chunk-${padded}.sql`);
    const stream = createWriteStream(file, { encoding: "utf8" });
    stream.write(sql);
    stream.end();
    await new Promise((res, rej) => {
      stream.on("finish", res);
      stream.on("error", rej);
    });
    chunks.push({ file, rows: buffer.length, bytes: sql.length, tables: [...new Set(buffer.map((r) => r.table))] });
    buffer = [];
    bufferBytes = 0;
    rowStart = totalRows + 1;
    onProgress?.(chunkNumber, totalRows);
  };

  for await (const sourceRow of rows) {
    // Map source columns to target DDL order via the shared schema map.
    const mapped = mapRowToTarget(
      sourceRow.table,
      sourceRow.columns,
      sourceRow.values,
      tableColumns[sourceRow.table],
    );
    buffer.push({ table: sourceRow.table, values: mapped.values });
    // Approximate byte cost: the rendered INSERT.
    const approxBytes = rowToInsert(tableColumns[sourceRow.table], mapped.values).length + 2;
    bufferBytes += approxBytes;
    totalRows += 1;
    if (buffer.length >= maxRows || bufferBytes >= maxBytes) {
      await flush();
    }
  }
  await flush();

  // Rewrite the chunksTotal in every chunk header now that we know it.
  // (Only the cosmetic comment; chunk content is unchanged.)
  // Skip the rewrite when there's only one chunk - the header already
  // self-references. The cosmetic correction below is honest only when
  // we wrote the files in this run.
  if (chunks.length > 1) {
    const { readFileSync, writeFileSync } = await import("node:fs");
    for (const chunk of chunks) {
      const txt = readFileSync(chunk.file, "utf8");
      const patched = txt.replace(
        /^(-- chunk \d+ of )0( \(rows )/m,
        `$1${chunks.length}$2`,
      );
      if (patched !== txt) writeFileSync(chunk.file, patched, "utf8");
    }
  }

  return { chunks, totalRows, outDir };
}

/** Read db/schema.sqlite.sql (or override) and produce the
 *  tableColumns map the chunker needs. Thin wrapper to keep the CLI
 *  call-site compact. */
export function readTableColumns(ddlPath) {
  return parseTargetSchema(ddlPath).tableColumns;
}
