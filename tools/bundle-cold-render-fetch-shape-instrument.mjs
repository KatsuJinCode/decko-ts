// tools/bundle-cold-render-fetch-shape-instrument.mjs — build the
// cold-render fetch-shape instrument into a plain-ESM file that node runs
// directly.
//
// WHY A BUILD STEP: the instrument imports the engine from TypeScript
// sources (src/card/fetch.ts, src/card/render.ts,
// src/card/drivers/bunny-db.ts) and the repo has no tsx/ts-node — its only
// TypeScript execution paths are vitest (slow to start, and its output is
// buffered until the run finishes, which is the wrong shape for an
// instrument you drive interactively) and the Bunny edge bundle. esbuild is
// already the bundler for the deployable artifact, so the same one is used
// here: same sources, no second toolchain.
//
//   node tools/bundle-cold-render-fetch-shape-instrument.mjs
//   node benchmarks/cold-render/measure-cold-render-fetch-shape.mjs --names Laundry
//
// Output: benchmarks/cold-render/measure-cold-render-fetch-shape.mjs
// node: builtins stay external (the instrument only uses node:fs).

import { build } from "esbuild";
import { mkdirSync } from "node:fs";
import { builtinModules } from "node:module";
import { resolve } from "node:path";

const here = resolve(process.cwd());
const out = resolve(here, "benchmarks/cold-render/measure-cold-render-fetch-shape.mjs");
mkdirSync(resolve(here, "benchmarks/cold-render"), { recursive: true });

const builtins = new Set([...builtinModules, ...builtinModules.map((n) => `node:${n}`)]);

await build({
  entryPoints: [resolve(here, "benchmarks/cold-render/instrument-cold-render-fetch-shape.ts")],
  outfile: out,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  external: [...builtins, "sass", "coffeescript"],
  banner: {
    js: "// GENERATED by tools/bundle-cold-render-fetch-shape-instrument.mjs — edit the .ts source, not this file.",
  },
  logLevel: "warning",
});

console.log(`bundled ${out}`);
