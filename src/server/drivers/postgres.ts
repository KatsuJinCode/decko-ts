// SQLDatabaseDriver over PostgreSQL.
//
// Ruby Decko runs on PostgreSQL as well as MySQL; this adapter lets the port
// serve a deck from PostgreSQL too. The engine writes SQLite-dialect SQL
// (src/server/driver.ts: one dialect, every adapter), so this adapter
// translates each statement to PostgreSQL before it runs. The translation is
// in translateSqliteToPostgres() below and covers the constructs the engine
// and its schema (db/schema.sqlite.sql) actually use; anything it does not
// recognize is passed through unchanged and fails loudly in PostgreSQL
// rather than being silently weakened.
//
// The adapter takes any client with a node-postgres-shaped `query(text,
// params)`: a `pg.Client` (one connection) for real servers, or a PGlite
// instance (PostgreSQL compiled to WebAssembly, in-process) for tests and
// local tooling. The engine never imports either SDK; the host constructs
// the client and hands it in.
//
// Transactions are native (BEGIN/COMMIT on the one connection the client
// holds). Do not pass a `pg.Pool`: a pool would run BEGIN and the work on
// different connections.

import type { SQLDatabaseDriver, SQLQueryResult, SQLStatement, SQLTransactionGuarantee } from "../driver.js";
import { TransactionGate } from "../driver.js";

/** The client surface this adapter needs. Both `pg.Client` (rowCount) and
 *  PGlite (affectedRows) satisfy it. */
export interface PostgresClientLike {
  query(text: string, params?: unknown[]): Promise<{
    rows: Record<string, unknown>[];
    rowCount?: number | null;
    affectedRows?: number;
    command?: string;
  }>;
  end?(): Promise<void>;
  close?(): Promise<void>;
}

export interface PostgresDriverOptions {
  client: PostgresClientLike;
  /** Close the client when the driver is closed. Default true. */
  ownsClient?: boolean;
}

const GUARANTEE: SQLTransactionGuarantee = {
  mechanism: "native",
  atomicOnFailure: true,
  crashRecovery: "database",
  readersIsolated: true,
  serializedWriters: "driver-object",
  atomicBatch: false,
  // PostgreSQL sequences never give back a value consumed by a rolled-back
  // transaction.
  idsReusedAfterRollback: false,
};

export class PostgresDriver implements SQLDatabaseDriver {
  readonly transactionGuarantee = GUARANTEE;
  private readonly client: PostgresClientLike;
  private readonly ownsClient: boolean;
  private readonly gate = new TransactionGate();
  /** Tables whose "id" is generated by a sequence (from translated
   *  AUTOINCREMENT DDL, or discovered on first explicit-id insert). */
  private readonly sequencedTables = new Map<string, boolean>();

  constructor(options: PostgresDriverOptions) {
    this.client = options.client;
    this.ownsClient = options.ownsClient ?? true;
  }

  async query<T = unknown>(sql: string, params: unknown[]): Promise<SQLQueryResult<T>> {
    const t = translateSqliteToPostgres(sql);
    if (t.skip) return { rows: [], rowsAffected: 0 };
    const res = await this.client.query(t.sql, params.map(toPgParam));
    const rows = res.rows.map(normalizeRow) as T[];
    const rowsAffected = Number(res.affectedRows ?? res.rowCount ?? 0);
    const result: SQLQueryResult<T> = { rows: t.returningId ? [] : rows, rowsAffected };
    if (t.insertTable !== undefined) {
      if (t.returningId && rows.length > 0) {
        const id = (rows[rows.length - 1] as Record<string, unknown>).id;
        if (id !== undefined && id !== null) result.lastInsertRowId = Number(id);
      }
      if (t.explicitId) await this.advanceSequence(t.insertTable);
    }
    return result;
  }

  async batch(statements: SQLStatement[]): Promise<SQLQueryResult[]> {
    const out: SQLQueryResult[] = [];
    for (const s of statements) out.push(await this.query(s.sql, s.params));
    return out;
  }

  transaction<R>(work: () => Promise<R>): Promise<R> {
    return this.gate.run(async () => {
      await this.client.query("BEGIN");
      try {
        const value = await work();
        await this.client.query("COMMIT");
        return value;
      } catch (error) {
        await this.client.query("ROLLBACK").catch(() => undefined);
        throw error;
      }
    });
  }

  async close(): Promise<void> {
    if (!this.ownsClient) return;
    if (this.client.close) await this.client.close();
    else if (this.client.end) await this.client.end();
  }

  /** An insert that names "id" explicitly does not draw from the sequence;
   *  move the sequence past it so the next generated id does not collide
   *  (SQLite's AUTOINCREMENT does this itself). */
  private async advanceSequence(table: string): Promise<void> {
    if (this.sequencedTables.get(table) === false) return;
    const seq = await this.client.query(`SELECT pg_get_serial_sequence($1, 'id') AS s`, [quoteIdent(table)]);
    const name = seq.rows[0]?.s as string | null | undefined;
    if (!name) {
      this.sequencedTables.set(table, false);
      return;
    }
    this.sequencedTables.set(table, true);
    await this.client.query(
      `SELECT setval($1, GREATEST((SELECT COALESCE(MAX(id), 0) FROM ${quoteIdent(table)}), (SELECT last_value FROM ${name})), true)`,
      [name],
    );
  }
}

function quoteIdent(name: string): string {
  return `"${name.replace(/"/g, '""')}"`;
}

function toPgParam(value: unknown): unknown {
  if (typeof value === "boolean") return value ? 1 : 0;
  if (typeof value === "bigint") return value.toString();
  return value;
}

/** PostgreSQL reports booleans and 64-bit integers where SQLite reports
 *  0/1 and numbers; the engine was written against SQLite's shapes. */
function normalizeRow(row: Record<string, unknown>): Record<string, unknown> {
  for (const k of Object.keys(row)) {
    const v = row[k];
    if (typeof v === "boolean") row[k] = v ? 1 : 0;
    else if (typeof v === "bigint") row[k] = Number(v);
  }
  return row;
}

