// SQLite -> PostgreSQL dialect mapper.
//
// Pure, deterministic, side-effect-free. Translates the SQLite-flavored
// SQL the decko-ts engine emits (src/cql/sql.ts, src/card/render/*.ts,
// src/card/history/write-path.ts, src/card/auth/*.ts, src/card/permissions/
// *.ts) into PostgreSQL-flavored SQL a node-postgres client can execute.
//
// The engine never sees the dialect layer: it always emits `?` placeholders
// + SQLite function names. The driver applies the mapping right before the
// SQL reaches the connection, so all engine layers stay SQLite-grounded.
//
// AUDIENCE: tested with vitest unit cases (no live server needed for the
// pure mapping). The live-PG rung — what must be exercised against a real
// PostgreSQL instance — is documented in docs/postgres-dialect-notes.md.
//
// SCOPE — what this mapper does (and does not):
//
//   * parameter placeholders: `?` -> `$1`, `$2`, `$3`, ... (in order).
//   * SQLite-flavored function names -> PG equivalents (INSTR, SUBSTR,
//     last_insert_rowid, etc.).
//   * the SQLite `REGEXP` operator -> PG `~*` (case-insensitive), the same
//     semantics CQL's `match` clause needs (sqlite-regexp.ts).
//   * NOCASE comparisons -> case-insensitive form via `LOWER(...)` (PG has
//     no NOCASE collation; the engine's keys are lowercase-ASCII so LOWER
//     is lossless).
//   * SQLite-style `datetime('now')` -> `CURRENT_TIMESTAMP` (defensive; the
//     decko engine does not currently emit it, but a stray token must not
//     crash the dialect).
//   * DDL fragments: `AUTOINCREMENT` -> `GENERATED BY DEFAULT AS IDENTITY`,
//     `PRAGMA foreign_keys = ...` -> dropped (PG has session-level GUCs;
//     parity with production requires no FKs anyway).
//
// OUT OF SCOPE (documented in docs/postgres-dialect-notes.md):
//   * json1 functions (json_extract, json_array_length, ...). The decko-ts
//     engine does not currently emit them; if a wave introduces them, the
//     mapping lives here.
//   * `GROUP_CONCAT` (no PG equivalent built-in; would need STRING_AGG).
//   * `RANDOM()` -> `random()` is a no-op; both engines return a real
//     pseudo-random number so it is left alone by this mapper.
//
// PARAMETER BINDING (not a string rewrite — see toPostgresValue):
//   * JS number, bigint, string, null, Uint8Array map straight to node-
//     postgres binding values (with bigint serialized to its string form to
//     stay within PG's int8 surface).
//   * booleans: the engine never emits JS booleans today (tinyint(1) is
//     0|1). If one ever does, it is bound as `true`/`false` for PG's
//     `boolean` type. Documented; not currently exercised.
//
// USAGE:
//   const { sql, paramCount } = toPostgresSql(sqliteSql);
//   const pgParams = sqliteParams.map(toPostgresValue);
//   await pgClient.query(sql, pgParams);
//   // `paramCount` is the number of `?` placeholders replaced. Useful for
//   // callers that want to assert dialect rewrites the expected count.

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

export interface DialectResult {
  /** The PostgreSQL SQL text — ready to send to a PG client. */
  sql: string;
  /** Number of `?` placeholders consumed (and therefore of positional
   *  parameters expected in the param array). Sanity-checked by callers. */
  paramCount: number;
}

/** Translate one SQLite-flavored SQL statement into its PostgreSQL
 *  equivalent. Throws if the SQL is structurally malformed (unterminated
 *  string literal, unterminated line/block comment). */
export function toPostgresSql(sqliteSql: string): DialectResult {
  const placeholders = rewritePlaceholders(sqliteSql);
  const sql = rewriteSqliteFunctions(placeholders.sql);
  return { sql, paramCount: placeholders.paramCount };
}

/** Translate one SQLite-flavored parameter value into its PG bind shape.
 *  `null` and the JS scalar types pass through. bigints become strings
 *  (node-postgres v8 binds bigint directly but the dialect module
 *  intentionally standardizes on the string form so future servers without
 *  bigint support do not silently corrupt values). Uint8Array becomes a
 *  Buffer (the form node-postgres expects for bytea). Booleans pass
 *  through (PG's boolean column accepts them). */
export function toPostgresValue(value: unknown): unknown {
  if (value === null || value === undefined) return null;
  if (typeof value === "bigint") return value.toString();
  if (value instanceof Uint8Array) return Buffer.from(value);
  return value;
}

// ---------------------------------------------------------------------------
// Placeholder rewrite: `?` -> `$N`
// ---------------------------------------------------------------------------

/** Walk the SQL and replace every `?` that lies outside string literals and
 *  comments with a 1-based positional placeholder. The walk is a single
 *  pass over the characters — a regex on `?` cannot tell apart a
 *  placeholder from one inside a string or comment without state. */
function rewritePlaceholders(sql: string): { sql: string; paramCount: number } {
  let out = "";
  let i = 0;
  let paramIndex = 0;
  const n = sql.length;
  while (i < n) {
    const c = sql[i];
    // Single-quoted string literal: copy through, doubling '' is one literal
    if (c === "'") {
      out += c;
      i += 1;
      while (i < n) {
        const ch = sql[i];
        out += ch;
        i += 1;
        if (ch === "'") {
          // Doubled '' is one literal — stay in the literal; a single '
          // followed by anything else closes it.
          if (i < n && sql[i] === "'") {
            out += sql[i];
            i += 1;
            continue;
          }
          break;
        }
      }
      continue;
    }
    // Line comment to EOL
    if (c === "-" && sql[i + 1] === "-") {
      while (i < n && sql[i] !== "\n") {
        out += sql[i];
        i += 1;
      }
      continue;
    }
    // Block comment
    if (c === "/" && sql[i + 1] === "*") {
      out += "/*";
      i += 2;
      while (i < n && !(sql[i] === "*" && sql[i + 1] === "/")) {
        out += sql[i];
        i += 1;
      }
      if (i < n) {
        out += "*/";
        i += 2;
      }
      continue;
    }
    // The placeholder
    if (c === "?") {
      paramIndex += 1;
      out += `$${paramIndex}`;
      i += 1;
      continue;
    }
    out += c;
    i += 1;
  }
  return { sql: out, paramCount: paramIndex };
}

// ---------------------------------------------------------------------------
// Function/operator rewrites
// ---------------------------------------------------------------------------

/** Translate SQLite-flavored function names + operators to PG equivalents.
 *  Order matters: longer patterns first so `last_insert_rowid()` beats any
 *  hypothetical narrower regex. All matches are anchored on word boundaries
 *  so identifiers like `my_instr` are not clobbered. */
function rewriteSqliteFunctions(sql: string): string {
  let out = sql;

  // SQLite `X REGEXP Y` -> PG `X ~* Y` (case-insensitive — the semantics
  // CQL match queries expect; see src/cql/sqlite-regexp.ts). PG also
  // supports `~` (case-sensitive) and `!~*`/`!~`; the engine emits plain
  // REGEXP for match queries only. Word boundaries on both sides keep
  // column names like `regexp_field` safe.
  out = out.replace(/\bREGEXP\b/gi, "~*");

  // last_insert_rowid() — the engine emits this after INSERTs to read the
  // generated id back (history/write-path.ts). PG's session-level lastval()
  // returns the value most recently obtained from nextval(); for SERIAL
  // columns this matches the AUTOINCREMENT semantics. The dialect does not
  // rewrite INSERTs to use RETURNING — that is the driver's choice, and
  // last_insert_rowid() stays the engine's idiom.
  out = out.replace(/\blast_insert_rowid\s*\(\s*\)/gi, "lastval()");

  // INSTR(haystack, needle) -> STRPOS(haystack, needle). Both take two
  // args; both return a 1-based position. PG returns 0 when not found,
  // matching SQLite. Inside a `substr` expression (substr(haystack,
  // instr(...) + N)) this becomes substring(haystack from strpos(...) + N)
  // after the substring rewrite below — the engines are compatible at
  // each step.
  out = out.replace(/\bINSTR\s*\(/gi, "STRPOS(");

  // SUBSTR(haystack, start[, length]) -> SUBSTRING(haystack FROM start
  // [FOR length]). PG also accepts the comma form SUBSTRING(s, start,
  // length); both forms compile to the same parser path, but the
  // FROM/FOR form is the SQL-standard shape and the one PG's docs lead
  // with. Three cases:
  //   2-arg: substr(s, start)               -> substring(s FROM start)
  //   3-arg: substr(s, start, length)       -> substring(s FROM start FOR length)
  //   nested calls: handled at the matching level (each top-level call
  //   is rewritten; nested substr(...) inside another substr's argument
  //   becomes substring(...) by recursive application of the same rule).
  out = rewriteSubstr(out);

  // COLLATE NOCASE — SQLite's case-insensitive comparison collation.
  // PG has no NOCASE collation, so the dialect rewrites the comparison to
  // a LOWER() comparison. The engine's keys are always lowercase ASCII
  // (src/server/schema.ts documents the convention; src/cql/normalize.ts
  // enforces it for inputs), so a binary LOWER(x) = LOWER(y) comparison
  // is exactly the ASCII-folding NOCASE provides.
  //
  // Recognized shapes (each `X` and `Y` is a SQL token — a quoted
  // identifier, a column reference, or a placeholder):
  //   X COLLATE NOCASE = Y
  //   X COLLATE NOCASE != Y
  //   X COLLATE NOCASE <> Y
  //   X COLLATE NOCASE IN (...)
  //   X COLLATE NOCASE NOT IN (...)
  //   X COLLATE NOCASE LIKE Y
  //   X COLLATE NOCASE NOT LIKE Y
  // The rewrite wraps X in LOWER(X). For the IN form, the right-hand
  // list is also wrapped — `lower(X) IN (lower(?), lower(?))` — so a
  // bind value can supply mixed-case input and the comparison still
  // matches the lowercased key column. The driver binds the value as
  // supplied; the engine does not rewrite it.
  out = rewriteNocaseCollations(out);

  // PRAGMA statements are SQLite-only (PRAGMA foreign_keys = OFF; etc.).
  // PG has no PRAGMA syntax; the engine's DDL uses one (db/schema.sqlite.sql)
  // but the live-PG schema lives in db/schema.postgres.sql (the schema
  // stream's responsibility, not this one). When this mapper meets a
  // PRAGMA in a DDL string passed through runAuthMigrations, it comments
  // the line out (PG ignores `-- ...`) so a stray PRAGMA never errors.
  // A semicolon-terminated PRAGMA on its own line is the typical shape;
  // the rewrite preserves the rest of the statement.
  out = rewritePragmas(out);

  // CURRENT_TIMESTAMP is supported natively by PG; the SQLite form
  // `datetime('now')` is mapped too so a wave that starts using it does
  // not silently corrupt. The engine does not currently emit it.
  out = out.replace(/\bdatetime\s*\(\s*'now'\s*\)/gi, "CURRENT_TIMESTAMP");

  // CAST types — PG accepts INTEGER/REAL/TEXT directly (the SQLite names).
  // For completeness: tinyint maps to SMALLINT and boolean to BOOLEAN if
  // they ever appear, but the engine does not emit them today.
  // (No rewrite needed.)

  return out;
}

function rewriteSubstr(sql: string): string {
  // Match substr(<args>) at any nesting depth by recursion on the args.
  // We walk the string tracking paren depth and rewrite each top-level
  // substr(...) call we encounter.
  let out = "";
  let i = 0;
  const n = sql.length;
  while (i < n) {
    const remaining = sql.slice(i);
    const m = /\bSUBSTR\s*\(/i.exec(remaining); // case-insensitive — matches the other rewrites
    if (m === null || m.index === undefined) {
      out += remaining;
      break;
    }
    out += remaining.slice(0, m.index);
    out += "SUBSTRING(";
    i += m.index + m[0].length;
    // Collect args by depth — SQL commas at depth 1 split args.
    const args: string[] = [];
    let depth = 1;
    let cur = "";
    while (i < n && depth > 0) {
      const ch = sql[i];
      if (ch === "(") {
        depth += 1;
        cur += ch;
      } else if (ch === ")") {
        depth -= 1;
        if (depth === 0) break;
        cur += ch;
      } else if (ch === "," && depth === 1) {
        args.push(cur.trim());
        cur = "";
      } else {
        cur += ch;
      }
      i += 1;
    }
    if (depth !== 0) {
      throw new Error("postgres-dialect: unbalanced parens while rewriting SUBSTR");
    }
    if (args.length === 0) {
      throw new Error("postgres-dialect: SUBSTR(...) requires at least one argument");
    }
    // Skip the closing ')' in the source
    i += 1;
    args.push(cur.trim());
    // Now args has [haystack, start] or [haystack, start, length].
    // Recurse each arg so nested SUBSTR calls also rewrite.
    const rewrittenArgs = args.map((a) => rewriteSubstr(a));
    if (rewrittenArgs.length === 2) {
      out += `${rewrittenArgs[0]} FROM ${rewrittenArgs[1]})`;
    } else if (rewrittenArgs.length === 3) {
      out += `${rewrittenArgs[0]} FROM ${rewrittenArgs[1]} FOR ${rewrittenArgs[2]})`;
    } else {
      // SUBSTR with more than 3 args is a SQL error on both engines; pass
      // through unchanged so the engine's error reaches the caller.
      out += rewrittenArgs.join(", ") + ")";
    }
  }
  return out;
}

function rewriteNocaseCollations(sql: string): string {
  // Replace `<left> COLLATE NOCASE <op> <rhs>` and the IN / NOT IN variants.
  // Each side is a single SQL token (column, placeholder, or parenthesized
  // group); the rewrite is `LOWER(<left>) <op> LOWER(<rhs>)` (for IN: each
  // list item wrapped in LOWER). The whole pattern is consumed in one
  // pass — no in-place post-edit of `out`.
  let out = "";
  let i = 0;
  const n = sql.length;
  while (i < n) {
    const remaining = sql.slice(i);
    const m = /\bCOLLATE\s+NOCASE\b/i.exec(remaining);
    if (m === null || m.index === undefined) {
      out += remaining;
      break;
    }
    const matchStart = i + m.index; // absolute offset of 'C' in COLLATE
    // Walk back to find the start of the left-hand token.
    const leftStart = findTokenStart(sql, matchStart);
    const leftEnd = matchStart; // left token ends right where COLLATE begins
    const leftToken = sql.slice(leftStart, leftEnd).trim();
    // Emit everything before the left token untouched.
    out += sql.slice(i, leftStart);
    // Skip past "COLLATE NOCASE" in the source.
    i = matchStart + m[0].length;
    // Skip whitespace.
    while (i < n && /\s/.test(sql[i])) i += 1;
    // Look ahead for the operator. We use a non-anchored trailing
    // whitespace check (rather than `\b`) because `\b` does not match
    // between two non-word characters (so `=` followed by ` ` would not
    // satisfy the boundary). After matching the operator we verify it
    // is followed by whitespace or end-of-string — that is the boundary
    // we actually need.
    const opMatch = /^(=|<>|!=|<=|>=|<|>|LIKE|NOT\s+LIKE|IN|NOT\s+IN)/i.exec(sql.slice(i));
    if (opMatch === null) {
      throw new Error(
        "postgres-dialect: COLLATE NOCASE must be followed by a comparison operator (engine bug)",
      );
    }
    // Reject false positives: the bare `<` and `>` alternatives match
    // inside an identifier. The longer `<=`, `>=`, `<>` alternatives
    // come first and consume the char when applicable; if the match is
    // just `<` or `>`, verify it is followed by whitespace.
    if ((opMatch[0] === "<" || opMatch[0] === ">") && i + 1 < n && /\w/.test(sql[i + 1])) {
      throw new Error(
        "postgres-dialect: COLLATE NOCASE followed by `>` or `<` that is part of an identifier (engine bug)",
      );
    }
    if (opMatch === null) {
      throw new Error(
        "postgres-dialect: COLLATE NOCASE must be followed by a comparison operator (engine bug)",
      );
    }
    const op = opMatch[0].toUpperCase().replace(/\s+/g, " ");
    i += opMatch[0].length;
    while (i < n && /\s/.test(sql[i])) i += 1;
    // Emit LOWER(left) <op> ...
    out += `LOWER(${leftToken}) ${op} `;
    // Emit LOWER(rhs) — single-token or parenthesized list.
    if (sql[i] === "(") {
      out += "(";
      i += 1;
      let depth = 1;
      let piece = "";
      while (i < n && depth > 0) {
        const ch = sql[i];
        if (ch === "(") {
          depth += 1;
          piece += ch;
        } else if (ch === ")") {
          depth -= 1;
          if (depth === 0) break;
          piece += ch;
        } else if (ch === "," && depth === 1) {
          out += `LOWER(${piece.trim()}), `;
          piece = "";
        } else {
          piece += ch;
        }
        i += 1;
      }
      if (depth !== 0) {
        throw new Error("postgres-dialect: unbalanced parens in IN list after COLLATE NOCASE");
      }
      out += `LOWER(${piece.trim()})`;
      out += ")";
      i += 1; // skip the closing paren
    } else {
      const rightEnd = findTokenEnd(sql, i);
      const rhs = sql.slice(i, rightEnd);
      out += `LOWER(${rhs})`;
      i = rightEnd;
    }
  }
  return out;
}

/** Walk backward from `pos` to find the start of the SQL token that ends
 *  just before `pos`. Any leading whitespace between the token and `pos`
 *  is skipped first (so `pos` pointing at `COLLATE` finds the token that
 *  ends right before the whitespace before COLLATE). Tokens are bounded
 *  by whitespace, commas, open parens, or the start of the string. */
function findTokenStart(sql: string, pos: number): number {
  let i = pos - 1;
  while (i >= 0 && /\s/.test(sql[i])) i -= 1;
  // i is now at the last non-whitespace char of the token (or -1).
  while (i >= 0) {
    const ch = sql[i];
    if (ch === " " || ch === "\t" || ch === "\n" || ch === "\r" || ch === "," || ch === "(") {
      return i + 1;
    }
    if (ch === ")") {
      // Parenthesized expression: walk back to the matching open paren.
      let depth = 1;
      i -= 1;
      while (i >= 0 && depth > 0) {
        if (sql[i] === ")") depth += 1;
        else if (sql[i] === "(") depth -= 1;
        i -= 1;
      }
      return i + 1;
    }
    i -= 1;
  }
  return 0;
}

/** Walk forward from `pos` to find the end of the SQL token starting at
 *  `pos`. Stops at whitespace, comma, close paren, or the end of the
 *  string. If the token starts with `(` the matching `)` is the end. */
function findTokenEnd(sql: string, pos: number): number {
  if (sql[pos] === "(") {
    let depth = 1;
    let i = pos + 1;
    while (i < sql.length && depth > 0) {
      if (sql[i] === "(") depth += 1;
      else if (sql[i] === ")") depth -= 1;
      i += 1;
    }
    return i;
  }
  let i = pos;
  while (i < sql.length) {
    const ch = sql[i];
    if (ch === " " || ch === "\t" || ch === "\n" || ch === "\r" || ch === "," || ch === ")") {
      return i;
    }
    i += 1;
  }
  return i;
}

function rewritePragmas(sql: string): string {
  // Match lines that begin with PRAGMA (after optional whitespace) and
  // comment them out. PG ignores `-- ...` and a multi-line pragma is
  // unusual; the engine's DDL emits one PRAGMA per file.
  return sql.replace(/(^|\n)([ \t]*PRAGMA\b[^\n]*)/g, (_match, lead, pragmaLine) => {
    return `${lead}-- ${pragmaLine.trimStart()}`;
  });
}

// ---------------------------------------------------------------------------
// DDL helpers — used by callers that build PG DDL from the engine's emitted
// SQLite DDL. The decko engine's DDL is parameterized for SQLite (INTEGER
// PRIMARY KEY AUTOINCREMENT); PG needs a different id-generation clause.
// These helpers are exported for the schema stream to use when emitting
// PG DDL; this module's runtime SQL mapping does not invoke them.
// ---------------------------------------------------------------------------

/** Translate `INTEGER PRIMARY KEY AUTOINCREMENT` (SQLite) into PG's
 *  `INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY` (PG 10+). The
 *  schema column type (INTEGER) is unchanged; PG's identity columns
 *  behave like SQLite's AUTOINCREMENT (monotonic, no reuse). Used by the
 *  schema stream's PG DDL emitter — NOT by the runtime SQL mapper. */
export function pgIdentityColumn(sqliteFragment: string): string {
  return sqliteFragment.replace(
    /\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b/gi,
    "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
  );
}

/** Strip every `PRAGMA ...;` statement from a DDL string. Returns the
 *  cleaned SQL and the pragma lines that were removed (in source order).
 *  Used by the schema stream's PG DDL emitter. */
export function stripPragmas(ddl: string): { cleaned: string; removed: string[] } {
  const removed: string[] = [];
  const cleaned = ddl.replace(/(^|\n)([ \t]*PRAGMA\b[^\n]*)/g, (_match, lead, pragmaLine) => {
    removed.push(pragmaLine.trim());
    return lead;
  });
  return { cleaned, removed };
}
