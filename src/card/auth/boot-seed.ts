/** The holder ids of the +*account junctions the CORPUS itself ships (the
 *  dump deck's Sign up+*account, User+*account and Decko Bot+*account rows,
 *  all bot-created). Ruby's census excludes them through
 *  `creator_id: ["ne", DeckoBotID]` (auth/setup.rb:43-46); this engine's
 *  census excludes shipped accounts by HOLDER (first-run-setup.ts, the
 *  one-actor split the port documents there) - so the corpus's shipped
 *  holders join the exclusion set, and a fresh corpus deck reads 0 exactly
 *  as Ruby's fresh deck does. */
export function corpusShippedAccountHolderIds(
  cards: readonly DefaultsFixtureCardRow[],
): number[] {
  const accountCard = cards.find((card) => card.codename === "account");
  if (accountCard === undefined) return [];
  return cards
    .filter((card) => card.rightId === accountCard.id)
    .map((card) => card.leftId)
    .filter((id): id is number => id !== null);
}

/**
 * Seed a fresh deck: schema-first is the CALLER's contract (Ruby: db:setup's
 * schema:load precedes db:seed — card.rake:4-6, db/seeds.rb:3; here the
 * deploy stream's / the storage builder's schema application), then
 *
 *   layer A — the fresh-deck fixture as direct INSERTs (Cardio::Seed.load's
 *             FixtureSet semantics): seed_mods[0]'s DEFAULTS corpus
 *             (the deploy seed asset, 604 cards + the corpus's own
 *             action/act/reference rows - register row 12's close), or the
 *             eleven-row core fixture at its index-1 arm
 *             (CORE_FIXTURE_SEED_CARDS) when PORT_SEED_SOURCE names it;
 *   layer B — ACCOUNT_MOD_SEED_CARDS plus the shipped bot account, through
 *             the engine's CardActionEngine as the DeckoBot actor
 *             (Card.ensure! under Auth.as_bot — eat.rb:28, :38-45), each
 *             create carrying its real.yml codename. On the defaults corpus
 *             every row already exists, so the run is the ensure arm's
 *             no-op (repair without churn);
 *   layer C — the two mod real.yml seed tables, run in sequence through the
 *             same ensure machinery and the same act:
 *             MOD_CONTENT_SEED_CARDS (mod-content-seeds.ts) then
 *             MOD_REAL_YAML_SEED_CARDS (mod-realyml-seed-cards.ts). They are
 *             two lanes' views of the SAME eleven gem rows, so the second
 *             pass is a no-op update; both tables stay live because each
 *             carries its own oracle pin against the gems. Rows were
 *             reconciled at this merge — see mod-content-seeds.ts's header
 *             for the two that had drifted (HTML+description's name and the
 *             *tinyMCE block scalar's trailing newline).
 *   layer D — the install-time mod card cascade (boot-mod-cards.ts), the
 *             port of Cardio::Mod.ensure_installed: the Mod cardtype and
 *             the *script / *style / *asset input / *asset output /
 *             style: mods / *all+*script dependency rows, then a
 *             "mod: <name>" card per mod in bundle order, each mod's
 *             "mod: <name>+*script" / "+*style" List cards for the asset
 *             trees the vendored manifests carry, and the two rule
 *             contents (*all+*script's fifteen items, style: mods's
 *             eighteen).
 *
 * After a successful run the deck is bootstrapped in actor.ts:50's sense:
 * actorBot/actorAnonymous resolve, resolveAccountCodenameIds (signin.ts)
 * returns the account field ids, and the first-run setup window can compute
 * its census. Nothing here opens that window: the census still counts REAL
 * holder accounts only — the seeded rows are the shipped accounts
 * (setup.rb:44's "every deck starts with two accounts"), excluded by holder
 * id exactly as Ruby's creator_id arm excludes them.
 */
export async function bootstrapFreshDeck(deps: BootSeedDeps): Promise<BootSeedResult> {
  const now = deps.now ?? (() => new Date());
  const stamp = sqlDateTime(now());

  // ---- layer A: the fresh-deck fixture, direct INSERT (FixtureSet.create_
  // fixtures). Ruby seeds seed_mods[0] - the DEFAULTS corpus (register row
  // 12's close, loaded by the boot from the deploy seed asset); the
  // eleven-row core corpus stays available at the index-1 arm it really
  // occupies (the CARD_UPDATE_SEED side).
  const layerA = await seedFreshDeckFixture(deps.driver, stamp, deps.defaultsCorpus);
  const coreRowsInserted = typeof layerA === "number" ? layerA : layerA.cards;
  const defaultsRowsInserted = typeof layerA === "number" ? undefined : layerA;

  // On the defaults corpus the boot is db:setup exactly: the corpus IS the
  // whole fresh deck, and Ruby's fresh-deck path runs no eat over it (the
  // eat machinery is `card update`, card.rake:22, an operator-driven run).
  // The ensure layers below would second-guess the corpus row by row - the
  // dump carries historical key forms a computed key does not always match
  // (the Anonymous row's stored key), so an ensure create there is a
  // DUPLICATE, not a repair - which is exactly the card-for-card match this
  // seed exists to land. They stay live on the index-1 arm, whose corpus
  // genuinely lacks the account system.
  if (defaultsRowsInserted !== undefined) {
    return {
      ok: true,
      coreRowsInserted,
      defaultsRowsInserted,
      modCardsCreated: [],
      modCardsUpdated: [],
    };
  }

  // ---- layer B needs the bot to act as (eat.rb:38-45 Auth.as_bot; the bot
  // row is layer A card 1, seed.rb:106-108's author).
  const bot = await actorBot(deps.driver);

  const fetcher = new FetchEngine(deps.driver);
  const engine = new CardActionEngine(fetcher, { actor: bot });
  const modCardsCreated: string[] = [];
  const modCardsUpdated: string[] = [];

  for (const seed of ACCOUNT_MOD_SEED_CARDS) {
    await ensureSeedCard(engine, seed, deps.driver, bot, modCardsCreated, modCardsUpdated);
  }

  // the shipped bot account (real.yml :203-206). An account is created with
  // its +*email (require_field :email, set/right/account.rb:8), so a missing
  // junction is created with the email as its subcard.
  const botAccount = await engine.fetch.fetchByName(DECKOBOT_ACCOUNT.junctionName);
  if (botAccount === undefined || botAccount.id === undefined) {
    await engine.createCard({
      name: DECKOBOT_ACCOUNT.junctionName,
      subcards: { "+*email": { content: DECKOBOT_ACCOUNT.email } },
    });
    modCardsCreated.push(DECKOBOT_ACCOUNT.junctionName, DECKOBOT_ACCOUNT.emailChildName);
  }
  await ensureNamed(engine, DECKOBOT_ACCOUNT.emailChildName, DECKOBOT_ACCOUNT.email, undefined, modCardsCreated, modCardsUpdated);

  // ---- layer C: the mod content seeds. Same ensure semantics (eat.rb:22-33),
  // same act, same create-or-update-by-name repair, two tables in sequence —
  // mod-content-seeds.ts first, then the realyml table (which carries the
  // Psych-tie-broken oracle and therefore gets the last word on any row the
  // two tables still disagree about).
  for (const seed of MOD_CONTENT_SEED_CARDS) {
    await ensureSeedCard(engine, seed, deps.driver, bot, modCardsCreated, modCardsUpdated);
  }

  for (const seed of MOD_REAL_YAML_SEED_CARDS) {
    await ensureSeedCard(engine, seed, deps.driver, bot, modCardsCreated, modCardsUpdated);
  }

  // ---- layer D: the install-time mod card cascade (Cardio::Mod.
  // ensure_installed, boot-mod-cards.ts): the mod cards, the mod asset
  // input cards, and the two asset lists the script and style bundles
  // read. Runs through the same engine and the same bot.
  const modCardCascade = await ensureInstalledModCards(engine, deps.driver);

  return {
    ok: true,
    coreRowsInserted,
    ...(defaultsRowsInserted !== undefined ? { defaultsRowsInserted } : {}),
    modCardsCreated,
    modCardsUpdated,
    modCardCascade,
  };
}

