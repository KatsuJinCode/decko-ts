// The boot-seed capability: create the account-system cards a fresh deck
// needs, so a newly provisioned deck is bootstrapped in actor.ts:50's sense —
// Anonymous/DeckoBot resolvable — and the permission system's role/account
// cards exist. Before this module the engine's own source stated the gap:
// first-run-setup.ts's deploy-profile note ("the engine has no mod-seeding
// capability to create them") and the account_system_absent gate reason.
//
// ---------------------------------------------------------------------------
// WHAT IS RUBY HERE (read before changing anything)
// ---------------------------------------------------------------------------
//
// ORDER: seed runs AFTER schema init, at install time — not per request.
//
//   mod/core/lib/tasks/card.rake:4-6
//     desc "Creates the database, loads the schema, initializes seed data, ..."
//     task setup: %w[db:setup card:mod:symlink]
//   db:setup is Rails' create + schema:load + seed, and the seed step is
//   db/seeds.rb:3 `Cardio::Seed.load` (card-1.110.0/db/seeds.rb).
//
// LOADER 1 — the core fixture (Cardio::Seed):
//   lib/cardio/seed.rb:12-18  `path` -> db_path :real -> seed.rb:61-63
//     Mod.fetch(seed_mods).subpath("data", "fixtures", env) — the fixture
//     directory mod/core/data/fixtures/real/.
//
//   [corrected 2026-10-20, register entry 12] THE CITED RULE RESOLVES A
//   DIFFERENT CORPUS THAN THE ONE TRANSCRIBED BELOW, and this file's own
//   sentence "Mod.fetch(seed_mods).subpath(...)" is what hides it. The
//   rule is faithful — seed.rb:62 really is
//   `Mod.fetch(seed_mods[index]).subpath "data", "fixtures", env` — but
//   seed.rb:8-9 calls it with index 0, and seed_mods[0] is NOT core:
//
//     lib/cardio/railtie.rb:6   config.seed_mods = [:core]
//     card-mod-defaults-0.20.0/lib/card/mod/defaults.rb:1
//       Cardio::Railtie.config.seed_mods.unshift :defaults
//     => seed_mods == [:defaults, :core] by the time db:setup runs
//
//   So a fresh Ruby deck seeds card-mod-defaults' data/fixtures/real/ —
//   604 cards — and this layer A transcribes mod/core's, index 1 —
//   11 cards. NOT a different transcription of the same corpus: a
//   DIFFERENT corpus. The ordering, the resolution rule and both
//   corpora's exact row counts are now ported and typed in
//   src/card/auth/seed-source.ts (census generated by
//   tools/oracle/seed-corpus-census.rb into
//   src/card/auth/seed-corpus-census.ts), which also carries the named
//   skip for the 604-row corpus. What this file transcribes is named
//   there as PORT_SEED_SOURCE, so the gap is a value to read rather than
//   a sentence to rediscover.
//
//   lib/cardio/seed.rb:20-22  `Cardio::Seed.load` =
//     ActiveRecord::FixtureSet.create_fixtures(path, load_tables) — DIRECT
//     ROW INSERTS, not card saves. No acts/actions are built for these rows;
//     current_revision_id stays NULL (the fixture carries no revision).
//   The fixture this ports verbatim is mod/core/data/fixtures/real/cards.yml
//   (11 cards, ids 1..11, every row creator_id 1 / updater_id 1 /
//   read_rule_class "*all" / read_rule_id 10 / trash false). The stamps are
//   Cardio::Seed's own: seed.rb:99-104 clean_time_and_user_stamps sets
//   creator_id/updater_id to the bot (author_id, seed.rb:106-108 =
//   Card::DeckoBotID — card 1 is the bot, cards.yml cards_001).
//
// LOADER 2 — mod-yaml ingestion (Cardio::Mod::Eat):
//   mod/core/lib/tasks/card.rake:22  task eat: "Ingests card data from mod
//     yaml" (default user: "Decko Bot"), run under card:update (:14) after
//     the schema migrations.
//   lib/cardio/mod/eat/edibles.rb:66-71  reads <mod>/data/<podtype>.yml
