// sync-migrations.mjs — make the D1 migration self-contained inside deploy/.
//
// Copies db/schema.sqlite.sql (the schema stream's source of truth) to
// deploy/migrations/0001-schema.sql so `wrangler d1 execute --file
// migrations/0001-schema.sql` (and `wrangler d1 migrations apply`) needs
// nothing outside this directory.
//
// Transformation (the only one, recorded in the generated header):
// - The PRAGMA line is dropped. The schema declares NO foreign keys
//   (verified — no FOREIGN KEY clause anywhere), so the pragma is
//   semantically moot, and D1 does not accept session PRAGMAs through the
//   execute path. Everything else is byte-verbatim.
//
// Run from anywhere: node deploy/sync-migrations.mjs  (paths are resolved
// relative to this file, not the cwd).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = join(HERE, "..", "db", "schema.sqlite.sql");
const TARGET = join(HERE, "migrations", "0001-schema.sql");

const source = readFileSync(SOURCE, "utf8");
const sourceSha = createHash("sha256").update(source, "utf8").digest("hex");

// Drop PRAGMA statements (whole-line, both the statement and its trailing
// semicolon); keep every other byte including comments.
const body = source
  .split("\n")
  .filter((line) => !/^\s*PRAGMA\b/i.test(line))
  .join("\n")
  .replace(/^\s*;\s*$/gm, "");

const header = [
  "-- ============================================================================ ",
  "-- 0001-schema.sql — GENERATED by deploy/sync-migrations.mjs. Do not edit.",
  "--",
  `-- Source: db/schema.sqlite.sql (sha256 ${sourceSha})`,
  "-- Generated: " + new Date().toISOString(),
  "-- Transformation: PRAGMA statements dropped (the schema declares no",
  "-- foreign keys, so the pragma is moot; D1 rejects session PRAGMAs on the",
  "-- execute path). Every other byte is verbatim from the source file.",
  "-- Re-generate after schema changes:  node deploy/sync-migrations.mjs",
  "-- ============================================================================",
  "",
].join("\n");

mkdirSync(dirname(TARGET), { recursive: true });
writeFileSync(TARGET, header + body.replace(/^\n+/, "") + "\n", "utf8");

const targetSha = createHash("sha256").update(header + body.replace(/^\n+/, "") + "\n", "utf8").digest("hex");
console.log(`sync-migrations: wrote ${TARGET}`);
console.log(`  source sha256: ${sourceSha}`);
console.log(`  target sha256: ${targetSha}`);
