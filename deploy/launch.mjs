function parseD1CreateOutput(stdout) {
  // wrangler 4 prints "database_id = \"<uuid>\"" on its own line in the JSON
  // output; on success the line `Created DB '<name>'` precedes the JSON.
  const m = stdout.match(/database_id\s*=\s*"([0-9a-f-]+)"/i) ?? stdout.match(/"database_id"\s*:\s*"([0-9a-f-]+)"/i);
  return m?.[1];
}

function parseSubdomainFromDeploy(stdout) {
  // wrangler prints "Published <name> (<version>) - https://<name>.<subdomain>.workers.dev"
  const m = stdout.match(/https:\/\/[^\s]+\.([a-z0-9-]+)\.workers\.dev/i);
  return m?.[1];
}

function patchWranglerToml(dbId) {
  const original = readFileSync(WRANGLER_TOML, "utf8");
  const patched = original.replace(
    /database_id\s*=\s*"[^"]*"/,
    `database_id = "${dbId}"`,
  );
  if (patched === original) {
    console.error(`launch: failed to patch ${relativeToRepo(WRANGLER_TOML)} (no database_id match).`);
    process.exit(1);
  }
  writeFileSync(WRANGLER_TOML, patched, "utf8");
  console.log(`  patched ${relativeToRepo(WRANGLER_TOML)} with database_id = ${dbId}`);
  console.log("");
}

/** Apply a SQL file in chunks of <=chunkSize statements via the splitter,
 *  using wrangler d1 execute --file <chunk.sql> per chunk. Each chunk is
 *  written to deploy/logs/ as a sibling file so the operator can re-apply
 *  a single chunk by hand if one fails. The single `--file` invocation is
 *  also kept as a fallback in the plan; this code path is what --execute
 *  actually calls. */
function applyFileChunked(stepId, sqlPath, { remote }) {
  const stmts = splitSeedStatements(readFileSync(sqlPath, "utf8"));
  const chunks = chunkStatements(stmts, DEFAULT_CHUNK_STATEMENTS);
  const tag = relativeToRepo(sqlPath);
  console.log(`==> ${stepId}: ${tag} (${stmts.length} statements, ${chunks.length} chunks of <=${DEFAULT_CHUNK_STATEMENTS})`);
  for (let i = 0; i < chunks.length; i++) {
    const chunkPath = join(LOG_ROOT, `${stepId}-chunk-${i + 1}-${randomUUID().slice(0, 8)}.sql`);
    writeFileSync(chunkPath, chunks[i].join(";\n") + ";\n", "utf8");
    const args = ["wrangler", "d1", "execute", DATABASE_NAME];
    if (remote) args.push("--remote");
    args.push("--file", chunkPath);
    const logPath = timestampedLogPath(`${stepId}-chunk-${i + 1}`);
    const cmd = ["npx", ...args].join(" ");
    console.log(`    chunk ${i + 1}/${chunks.length}: ${chunks[i].length} stmts`);
    console.log(`    $ ${cmd}`);
    const result = spawnSync("npx", args, { stdio: "pipe", encoding: "utf8", shell: process.platform === "win32" });
    const out = (result.stdout ?? "") + (result.stderr ?? "");
    writeFileSync(logPath, `=== $ ${cmd}\n\n${out}\n`, "utf8");
    const tail = out.length > TAIL_BYTES ? out.slice(out.length - TAIL_BYTES) : out;
    console.log(tail);
    console.log(`    full log: ${relativeToRepo(logPath)} (${out.length} bytes)`);
    if ((result.status ?? 1) !== 0) {
      console.error(`launch: chunk ${i + 1}/${chunks.length} of ${tag} FAILED.`);
      console.error(`        chunk file (re-applicable by hand): ${chunkPath}`);
      console.error(`        full log: ${relativeToRepo(logPath)}`);
      process.exit(1);
    }
  }
  console.log("");
}

function chunkStatements(stmts, size) {
  const chunks = [];
  for (let i = 0; i < stmts.length; i += size) chunks.push(stmts.slice(i, i + size));
  return chunks.length === 0 ? [[]] : chunks;
}

