// ---------------------------------------------------------------------------
// Local execution — boots real workerd via miniflare (the same path
// tests/deploy/deploy-worker-miniflare.test.ts proves is correct), applies
// the schema + seed through CloudflareD1Adapter (the same adapter the
// remote worker runs on), and runs the same smoke battery the remote path
// runs. No wrangler command touches the real account here.
// ---------------------------------------------------------------------------

if (flags.local) {
  preflight();
  console.log("decko-ts launch --local (miniflare + workerd; no account, no network)");
  ensureLogDir();

  // The dynamic import path mirrors the test: bundler is vite (vitest's
  // bundler; we use it here via the same call shape). miniflare 5 rejects
  // the classic v4 options shape (proved in
  // tests/server/drivers/d1-miniflare.test.ts) — convertV4MiniflareOptions
  // is the door. We import those packages by dynamic import so this script
  // still runs on a machine that has not installed vitest/miniflare into
  // PATH — the explicit error below names the dependency if it's missing.
  const startedAt = Date.now();
  const { Miniflare, convertV4MiniflareOptions } = await import("miniflare");
  const { build } = await import("vite");
  const { CloudflareD1Adapter } = await import("../src/server/drivers/d1.ts");

  // -- Bundle deploy/worker.ts with the production alias ---------------
  const cryptoShim = join(HERE, "shims", "node-crypto-shim.ts");
  const viteResult = await build({
    configFile: false,
    logLevel: "warn",
    resolve: { alias: [{ find: "node:crypto", replacement: cryptoShim }] },
    ssr: { noExternal: true },
    build: {
      write: false,
      minify: false,
      target: "es2022",
      ssr: true,
      rollupOptions: {
        input: join(HERE, "worker.ts"),
        output: { format: "esm", entryFileNames: "launch-worker.mjs" },
      },
    },
  });
  const outputs = (Array.isArray(viteResult) ? viteResult : [viteResult]);
  const bundle = outputs[0]?.output.find((chunk) => chunk.type === "chunk")?.code ?? "";
  if (bundle.length < 10_000) throw new Error("bundle suspiciously small (<10 KB) — worker graph did not come along");
  // Hygiene: the Web-standard claim covers EVERY node: specifier, not just
  // node:crypto — a crypto-only check let a raw "node:fs" through (hoisted
  // from src/card/render/coded-attachment-files.ts; now gated behind a
  // runtime probe), and workerd
  // rejects ANY node: module unless nodejs_compat is on, which this deploy
  // deliberately is not. The match is anchored to import/require syntax
  // (from "node:x" | import("node:x") | require("node:x")) so doc comments
  // and the runtime probe's own string argument never false-positive.
  const nodeImport = bundle.match(
    /(?:from\s*|import\s*\(\s*|import\s+|require\s*\(\s*)["']node:[a-z_]+["']/,
  );
  if (nodeImport !== null) {
    throw new Error(
      `bundle imports a Node builtin (${nodeImport[0].trim()}) — ` +
        "workerd will refuse to boot it (no nodejs_compat on this deploy)",
    );
  }

  // -- Boot workerd ----------------------------------------------------
  const mf = new Miniflare(
    convertV4MiniflareOptions({
      modules: true,
      script: bundle,
      d1Databases: { DB: "decko-launch-local" },
    }),
  );
  const binding = await mf.getD1Database("DB");
  const adapter = new CloudflareD1Adapter(binding);

  // -- Apply schema (one statement at a time, the splitter's output) ----
  const migrations = splitSeedStatements(readFileSync(MIGRATIONS_FILE, "utf8"));
  for (const sql of migrations) {
    await adapter.query(sql, []);
  }
  console.log(`  schema: applied ${migrations.length} statements`);

  // -- Apply seed chunked through the same chunker --------------------
  const seedStmts = splitSeedStatements(readFileSync(SEED_FILE, "utf8"));
  const chunks = chunkStatements(seedStmts, DEFAULT_CHUNK_STATEMENTS);
  for (let i = 0; i < chunks.length; i++) {
    await adapter.batch(chunks[i].map((sql) => ({ sql, params: [] })));
  }
  console.log(`  seed: applied ${seedStmts.length} statements in ${chunks.length} chunks of <=${DEFAULT_CHUNK_STATEMENTS}`);

  // -- Smoke battery ---------------------------------------------------
  const base = "https://decko-launch-local.test";
  const smokeLog = timestampedLogPath("smoke-battery");
  const smokeLines = [];

  // 1. /_status
  const statusRes = await mf.dispatchFetch(`${base}/_status`);
  const statusBody = await statusRes.text();
  smokeLines.push(`GET /_status -> ${statusRes.status} ${statusBody.slice(0, 256)}`);

  // 2. / (Home render)
  const homeRes = await mf.dispatchFetch(`${base}/`);
  const homeHtml = await homeRes.text();
  smokeLines.push(`GET / -> ${homeRes.status} ${homeHtml.length}B html`);
  const depthOk =
    homeHtml.includes("Welcome to the decko-ts synthetic demo deck") &&
    homeHtml.includes("Section One rendered as a compound card") &&
    homeHtml.includes("History body text — the fourth inclusion level");

  // 3. /Home.json
  const jsonRes = await mf.dispatchFetch(`${base}/Home.json`);
  const jsonBody = await jsonRes.text();
  smokeLines.push(`GET /Home.json -> ${jsonRes.status} ${jsonBody.slice(0, 256)}`);

  // 4. /api/query
  const queryRes = await mf.dispatchFetch(`${base}/api/query`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ cql: { type: "Note", sort: "name" } }),
  });
  const queryBody = await queryRes.text();
  smokeLines.push(`POST /api/query -> ${queryRes.status} ${queryBody.slice(0, 256)}`);

  writeFileSync(smokeLog, smokeLines.join("\n") + "\n", "utf8");
  console.log("==> smoke battery");
  for (const line of smokeLines) console.log(`    ${line}`);
  console.log(`    full log: ${relativeToRepo(smokeLog)}`);
  console.log("");

  await mf.dispose();

  // -- Hard assertions (each ties to a test the deploy suite already pins) --
  let ok = true;
  if (statusRes.status !== 200) { console.error("launch --local FAIL: /_status != 200"); ok = false; }
  const statusJson = JSON.parse(statusBody);
  if (statusJson.database?.card_count !== 15) {
    console.error(`launch --local FAIL: /_status card_count=${statusJson.database?.card_count} (expected 15)`);
    ok = false;
  }
  if (!depthOk) { console.error("launch --local FAIL: depth-4 inclusion chain did not render"); ok = false; }
  if (jsonRes.status !== 200) { console.error("launch --local FAIL: /Home.json != 200"); ok = false; }
  const record = JSON.parse(jsonBody);
  if (record.type_name !== "Note" || record.key !== "home") {
    console.error(`launch --local FAIL: /Home.json record unexpected: ${JSON.stringify(record).slice(0, 200)}`);
    ok = false;
  }
  if (queryRes.status !== 200) { console.error("launch --local FAIL: /api/query != 200"); ok = false; }
  const queryResult = JSON.parse(queryBody);
  const ids = (queryResult.rows ?? []).map((r) => r.id).sort((a, b) => a - b);
  const expected = [10, 11, 12, 13, 14, 15, 16, 17, 18];
  if (JSON.stringify(ids) !== JSON.stringify(expected)) {
    console.error(`launch --local FAIL: /api/query rows=${JSON.stringify(ids)} (expected ${JSON.stringify(expected)})`);
    ok = false;
  }
  const secs = ((Date.now() - startedAt) / 1000).toFixed(1);
  if (!ok) process.exit(1);
  console.log(`launch --local OK in ${secs}s (schema + chunked seed + 4 smoke calls on miniflare-bound workerd).`);
  process.exit(0);
}

// ---------------------------------------------------------------------------
// Remote execution — each step runs through npx wrangler. The database_id
// step parses `wrangler d1 create` output to recover the printed id, then
// patches deploy/wrangler.toml in place (the same placeholder the
// deploy/README recipe names).
// ---------------------------------------------------------------------------

if (flags.execute) {
  preflight();
  ensureLogDir();
  console.log("decko-ts launch --execute (remote; this WILL create real resources on the Cloudflare account)");
  console.log("  log dir: " + relativeToRepo(LOG_ROOT));
  console.log("");

  // Step 1: d1 create
  const createStep = REMOTE_PLAN[0];
  const createResult = runStep(createStep);
  if (createResult.status !== 0) fail(createStep, createResult);
  const dbId = parseD1CreateOutput(createResult.stdout);
  if (dbId === undefined) {
    console.error("launch: could not parse database_id from wrangler d1 create output:");
    console.error(createResult.stdout);
    process.exit(1);
  }
  console.log(`  parsed database_id: ${dbId}`);
  console.log("");

  // Step 2: patch wrangler.toml
  patchWranglerToml(dbId);

  // Step 3: schema apply (we chunk it through the splitter ourselves for
  // symmetry with --local; wrangler d1 execute also accepts the whole file
  // but the chunked form is the same code path the migration tool uses).
  applyFileChunked("schema-apply", MIGRATIONS_FILE, { remote: true });

  // Step 4: chunked seed
  applyFileChunked("seed-apply", SEED_FILE, { remote: true });

  // Step 5: deploy
  const deployStep = REMOTE_PLAN[4];
  const deployResult = runStep(deployStep);
  if (deployResult.status !== 0) fail(deployStep, deployResult);

  // Step 6: smoke battery — find the printed subdomain from the deploy output
  const subdomain = parseSubdomainFromDeploy(deployResult.stdout);
  if (subdomain === undefined) {
    console.warn("launch: could not parse subdomain from wrangler deploy output; smoke battery skipped.");
    console.warn("        run the curl probes from deploy/README.md once you have the URL.");
    process.exit(0);
  }
  const base = `https://${WORKER_NAME}.${subdomain}.workers.dev`;
  for (const smoke of REMOTE_PLAN[5].extraSmokes) {
    const args = smoke.args.map((a) => a.replace("<subdomain>", subdomain));
    const logPath = timestampedLogPath(`smoke-${smoke.label.replace(/\W+/g, "-")}`);
    console.log(`==> smoke: ${smoke.label}`);
    const result = spawnSync("curl", ["-sS", ...args], { stdio: "pipe", encoding: "utf8" });
    const out = (result.stdout ?? "") + (result.stderr ?? "");
    writeFileSync(logPath, out, "utf8");
    const tail = out.length > TAIL_BYTES ? out.slice(out.length - TAIL_BYTES) : out;
    console.log(`    status: ${result.status}; bytes: ${out.length}`);
    console.log(tail);
    console.log(`    full log: ${relativeToRepo(logPath)}`);
    if (result.status !== 0) fail({ id: "smoke" }, { status: result.status, logPath });
    console.log("");
  }
  console.log("launch --execute OK. smoke battery against " + base + " passed.");
  console.log("Cleanup: node deploy/cleanup.mjs --yes");
  process.exit(0);
}

