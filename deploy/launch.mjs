// launch.mjs — one-command orchestrator for the demo deploy.
//
// What it does
// ============
//
// `node deploy/launch.mjs` (default, dry-run): prints the exact end-to-end
// plan to bring the demo Worker + D1 database up and exercise it. Touches
// nothing on the account; no wrangler command runs; no real D1 is created.
//
// `node deploy/launch.mjs --execute`: actually runs every step through
// `npx wrangler`. Steps: d1 create (if absent) -> wrangler.toml is updated
// with the printed id -> d1 execute --file migrations/0001-schema.sql -> d1
// execute --file seed/seed.sql in CHUNKED fashion (the importer's
// chunker, since the seed is a single INSERT run today and the chunker is
// the same one production migrations will use when cards grow past the
// single-batch limit) -> wrangler deploy -> smoke battery (/, /_status, one
// .json render, one /api/query). Every step's exact command and output goes
// to a timestamped log under deploy/logs/; the script prints a bounded tail
// of each log to stdout (an earlier run died printing a 335 KB vitest
// dump; the bound is enforced here).
//
// `node deploy/launch.mjs --local`: boots miniflare (real workerd, no
// Cloudflare account, no network) with the SAME artifacts the remote path
// uses, applies the schema + seed through the CloudflareD1Adapter (the
// adapter the worker runs on), and runs the same smoke battery against the
// local D1. This is the path that must work end-to-end today.
//
// What it does NOT do
// ===================
//
// - No `wrangler d1 create` or `wrangler deploy` against the real account
//   in `--local` mode (real-account calls only fire under
//   `--execute`).
// - No place where real production-deck member content is ever
//   introduced. The seed in deploy/seed/seed.sql is the synthetic demo
//   deck generated by deploy/seed.mjs (the data rule).
// - No git commits, no writes outside deploy/ + the user-provided seed
//   source. The log directory is gitignored.
//
// Provenance
// ==========
//
// This script coordinates the existing pieces; it does not reimplement
// them:
//   - wrangler CLI:  npx wrangler d1 create / execute / wrangler deploy
//   - schema:        deploy/migrations/0001-schema.sql (generated from
//                    db/schema.sqlite.sql by deploy/sync-migrations.mjs)
//   - seed:          deploy/seed/seed.sql (generated by deploy/seed.mjs)
//   - local proof:   tests/deploy/deploy-worker-miniflare.test.ts wires
//                    vite -> miniflare -> workerd the same way this script
//                    does for `--local`; that test pins every route we
//                    smoke below.
//
// The chunked seed import calls the importer's chunker
// (tools/migrate/import.mjs#splitSqlStatements) — the same splitter the
// migration tool uses, so a future migration that needs to apply a deck's
// worth of inserts sees the same chunk boundaries the chunker decides
// here for the seed.

import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { randomUUID } from "node:crypto";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(HERE, "..");
const LOG_ROOT = join(HERE, "logs");

const WORKER_NAME = "decko-ts-demo";
const DATABASE_NAME = "decko-ts-demo-db";
const MIGRATIONS_FILE = join(HERE, "migrations", "0001-schema.sql");
const SEED_FILE = join(HERE, "seed", "seed.sql");
const WRANGLER_TOML = join(HERE, "wrangler.toml");

// The seed today is ~8 KB and fits in a single batch; the chunker's job is
// to keep chunk boundaries stable when that grows. Default: one chunk per
// statement (semicolon-aware) — same as tools/migrate/import.mjs default
// behavior on a plain SQL file.
const DEFAULT_CHUNK_STATEMENTS = 50;

const argv = process.argv.slice(2);
const flags = {
  execute: argv.includes("--execute"),
  local: argv.includes("--local"),
  help: argv.includes("--help") || argv.includes("-h"),
};
if (flags.help) usage(0);
if (flags.execute && flags.local) {
  console.error("launch: --execute and --local are mutually exclusive.");
  process.exit(2);
}

