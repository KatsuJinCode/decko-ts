function printPlan(plan, label) {
  console.log(`decko-ts launch — ${label}`);
  console.log(`  worker:   ${WORKER_NAME}`);
  console.log(`  database: ${DATABASE_NAME}`);
  console.log(`  schema:   ${relativeToRepo(MIGRATIONS_FILE)}`);
  console.log(`  seed:     ${relativeToRepo(SEED_FILE)} (chunked via the migration importer's splitter)`);
  console.log(`  log dir:  ${relativeToRepo(LOG_ROOT)}`);
  console.log("");
  for (let i = 0; i < plan.length; i++) {
    const step = plan[i];
    console.log(`  [${i + 1}/${plan.length}] ${step.title}`);
    if (step.command !== null) {
      const preview = [step.command, ...step.args].join(" ");
      console.log(`      $ ${preview}`);
    }
    if (step.chunked) {
      const stats = splitSeedStats();
      console.log(`      (chunked: ${stats.statements} statements, ${stats.chunks} chunks of <=${DEFAULT_CHUNK_STATEMENTS})`);
    }
    if (step.extraSmokes) {
      for (const s of step.extraSmokes) {
        console.log(`      smoke: ${s.label}`);
        console.log(`        $ ${[step.command, ...s.args].join(" ")}`);
      }
    }
    if (step.onLocal?.kind === "skip") {
      console.log(`      (local: ${step.onLocal.note})`);
    }
    console.log("");
  }
}

// ---------------------------------------------------------------------------
// Seed chunking — uses the importer's splitter verbatim so the chunk
// boundaries on the deploy path match the chunk boundaries the migration
// tool applies to a deck's worth of inserts.
// ---------------------------------------------------------------------------

function splitSeedStatements(text) {
  const statements = [];
  let current = "";
  let quote = null;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quote !== null) {
      current += ch;
      if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === '"') {
      quote = ch;
      current += ch;
      continue;
    }
    if (ch === "-" && text[i + 1] === "-") {
      while (i < text.length && text[i] !== "\n") i++;
      current += " \n";
      continue;
    }
    if (ch === ";") {
      statements.push(current.trim());
      current = "";
      continue;
    }
    current += ch;
  }
  if (current.trim() !== "") statements.push(current.trim());
  return statements.filter((s) => s !== "" && !/^--/.test(s));
}

function splitSeedStats() {
  const text = readFileSync(SEED_FILE, "utf8");
  const stmts = splitSeedStatements(text);
  const chunks = Math.max(1, Math.ceil(stmts.length / DEFAULT_CHUNK_STATEMENTS));
  return { statements: stmts.length, chunks };
}

// ---------------------------------------------------------------------------
// Artifact preflight — every step that depends on a file asserts it exists;
// the local path REQUIRES the generated seed and migration to be present
// (the README names this contract: the deploy is self-contained).
// ---------------------------------------------------------------------------

function preflight() {
  for (const p of [MIGRATIONS_FILE, SEED_FILE, WRANGLER_TOML]) {
    if (!existsSync(p)) {
      console.error(`launch: required artifact missing: ${relativeToRepo(p)}`);
      console.error("        run: node deploy/sync-migrations.mjs && node deploy/seed.mjs");
      process.exit(3);
    }
  }
  const seedBytes = statSync(SEED_FILE).size;
  if (seedBytes >= 1024 * 1024) {
    console.error(`launch: seed exceeds the 1 MB deploy budget (${seedBytes} bytes). shrink the demo deck.`);
    process.exit(3);
  }
  const migBytes = statSync(MIGRATIONS_FILE).size;
  if (migBytes >= 5 * 1024 * 1024) {
    console.error(`launch: migrations file exceeds 5 MB (${migBytes} bytes). verify sync-migrations.`);
    process.exit(3);
  }
}

// ---------------------------------------------------------------------------
// Log helper — every spawned step writes to a timestamped file under
// deploy/logs/. We capture full output (an earlier run died printing 335 KB
// of vitest dump to the operator's terminal) and tail a bounded amount on
// stdout. Logs are written first, then the tail is printed.
// ---------------------------------------------------------------------------

function ensureLogDir() {
  if (!existsSync(LOG_ROOT)) mkdirSync(LOG_ROOT, { recursive: true });
}

function timestampedLogPath(stepId) {
  const stamp = new Date().toISOString().replace(/[:.]/g, "-");
  return join(LOG_ROOT, `${stamp}-${stepId}.log`);
}

const TAIL_BYTES = 4096; // bounded tail: enough for a real failure, never 335 KB

function runStep(step, env = {}) {
  if (step.command === null) return { status: 0, stdout: "", stderr: "", skipped: true };
  const logPath = timestampedLogPath(step.id);
  const cmd = [step.command, ...step.args].join(" ");
  console.log(`==> ${step.title}`);
  console.log(`    $ ${cmd}`);
  const result = spawnSync(step.command, step.args, {
    stdio: "pipe",
    shell: process.platform === "win32",
    encoding: "utf8",
    env: { ...process.env, ...env },
  });
  const out = (result.stdout ?? "") + (result.stderr ?? "");
  writeFileSync(logPath, `=== ${step.title}\n=== $ ${cmd}\n\n${out}\n`, "utf8");
  const tail = out.length > TAIL_BYTES ? out.slice(out.length - TAIL_BYTES) : out;
  console.log(tail.length > 0 ? tail : "    (no output)");
  console.log(`    full log: ${relativeToRepo(logPath)} (${out.length} bytes)`);
  console.log("");
  return { status: result.status ?? 1, stdout: result.stdout ?? "", stderr: result.stderr ?? "", logPath };
}

function fail(step, result) {
  console.error(`launch: step "${step.id}" FAILED (exit ${result.status}). full log: ${relativeToRepo(result.logPath ?? "(none)")}`);
  process.exit(1);
}

