    "                          touch nothing on the account, run no wrangler.",
    "  --execute               : run every step through npx wrangler,",
    "                          in order, with bounded stdout tailing.",
    "  --local                 : boot miniflare's real workerd + local D1",
    "                          (no account, no network), apply schema + seed",
