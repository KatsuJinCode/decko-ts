#!/usr/bin/env python3
"""build_corpus_v2.py -- corpus v2 for the M1 corpus-scale parity milestone.

The v1 corpus (benchmarks/corpus/) was structure-perfect but name-poor: the
production dump stores `cards.name IS NULL` for compound cards (the 2020
Lexicon convention), so 37,769 of 47,235 live cards had no name at all and
the junction topology existed only as left_id/right_id integers.

Corpus v2 rebuilds the corpus with REAL name structure under sanitization:

  1. Reconstruct every card's full name via the junction walk
     name(card) = name(left_id) + "+" + name(right_id)          (recursively,
     simple cards provide the atoms). The walk is the mechanism the proven
     name-correct extraction is built on; the extract
     (deck-migration/review/cards-extract.jsonl) is loaded as a
     CROSS-CHECK: every extract row that carries a real (non-placeholder)
     name must equal the walk's reconstruction exactly, and every live card
     must receive a non-null reconstructed name.

  2. Sanitize names per ATOM PART, not per card: each distinct atom part
     (a "+"-free name piece) gets an injective, deterministic, same-byte-
     length lowercase token. Engine-structural parts are preserved VERBATIM:
     star-rule parts ("*read", "*type", "*all", ...) and relative-reference
     parts ("_self", "_left", ...) -- these are Decko vocabulary, not
     source deck content, and rule names are load-bearing structure.
     Codenames are engine vocabulary and are likewise preserved verbatim.
     Part-count, part order, junction depth, and EXACT name byte length are
     preserved by construction (per-part equal length). Shared atoms map to
     shared tokens, so the name algebra (left/right composition) survives.

  3. Content sanitization reuses the proven v1 transform unchanged
     (byte-length-preserving filler, tag skeleton kept, inclusions resolved
     to the target's sanitized name, read-rule reader lists -> role
     buckets), now resolving inclusions against the RECONSTRUCTED names.

  4. card_references: ids, referee_id, ref_type, is_present preserved
     as-is. referee_key is sanitized through the SAME atom mapping (via the
     key form) so the references graph stays name-consistent; key parts
     that resolve to no atom fall back to v1-style deterministic
     collision-free same-length tokens.

  5. Everything else preserved exactly: ids, left_id/right_id, type_id,
     trash flags, creator/updater ids, read_rule_class/read_rule_id,
     timestamps shifted by the fixed v1 offset.

Inputs (both stay on this workstation; nothing original is emitted):
  - the production mysqldump (parsed linearly, proven parser reused from
    benchmarks/sanitize_corpus.py -- never a backtracking regex)
  - the proven extraction cards-extract.jsonl (name cross-check only)

Output: benchmarks/corpus-v2/bench-corpus-v2.sqlite3 +
        benchmarks/corpus-v2/corpus-v2-manifest.json

Determinism: same dump + same extract + same SEED -> identical corpus.
All PRNG streams are seeded from SEED ^ hash(atom/id); assignment orders
are sorted; no dict/set iteration feeds generated bytes. The proof is the
canonical digest (sha256 over id-ordered repr of every row), printed at the
end; the verify script re-derives it from the DB, and the determinism run
repeats the build under a different PYTHONHASHSEED.
"""

