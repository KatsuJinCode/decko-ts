// benchmarks/speed-ship/bundle.mjs — build render-page.ts into plain ESM that
// node runs directly (the repo has no tsx; esbuild is its bundler).
//
//   node benchmarks/speed-ship/bundle.mjs [outfile]
import { build } from "esbuild";
import { builtinModules } from "node:module";
import { resolve } from "node:path";

const here = resolve(process.cwd());
const builtins = new Set([...builtinModules, ...builtinModules.map((n) => `node:${n}`), "node:sqlite"]);
const outfile = resolve(here, process.argv[2] ?? "benchmarks/speed-ship/render-page.mjs");

await build({
  entryPoints: [resolve(here, "benchmarks/speed-ship/render-page.ts")],
  outfile,
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node22",
  keepNames: true,
  external: [...builtins, "sass", "coffeescript", "better-sqlite3"],
  banner: {
    js: "// GENERATED by benchmarks/speed-ship/bundle.mjs - edit the .ts sources.\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);",
  },
  logLevel: "warning",
});
console.log(`bundled ${outfile}`);
